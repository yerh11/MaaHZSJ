def pick_target(reachable):
    """按选路优先级挑下一个要走的节点。返回 `(node, 说明)`，挑不了就是 `(None, 为什么)`。

    用户 2026-10-02：「我希望脚本自己选，按照优先级」——这就是那天准备的那张表，
    从这天起真接进了 play()。**同级怎么取**也是当天定的：reachable 是 read_view
    给的、已经按读图顺序排好（先上后下、先左后右），取 `min` 天然就是"先读到的那一个"。

    三条规矩，**从上往下**判：

    1. **只有一条路 → 直接走**（用户 2026-10-03：「加一个保底机制, 如果只有一条路
       可以走 直接走」）。一条路时没有"选"，优先表无从谈起，问人也只是白停一次。
    2. **全是每层必走的出口**（`LAYER_EXITS`：「深入」下一层入口、「首领」守关 Boss）
       → 直接走。用户 2026-10-02：「一句游戏一共有六层, 每一层最后, 如深入, 首领,
       都是必走的」。判据是「**可前往的全是**这类出口」——和别的节点同屏时仍停车。
    3. 否则**按优先表**取最小号。

    优先表**没定过**的（读不清的标签、没见过的新节点）一律不猜，返回 None 让调用方
    停车问人——map.py 开头那段写着"真遇到要和别的节点二选一时先问清楚"。
    第 1 条正是那句话的另一半：**没有"二"的时候就不必问**（第 2 条同理，
    只是它管的是"都是出口"这一种特例）。
    """
    if not reachable:
        return None, "地图上没读到可前往节点"

    best = min(reachable, key=lambda r: priority(r["kind"]))
    p = priority(best["kind"])

    # **保底：只有一条路可走就直接走**（用户 2026-10-03 原话：「加一个保底机制,
    # 如果只有一条路可以走 直接走」）。
    # 只有一条路时根本没有"选"这回事——优先表、每层出口那两条都失去意义，
    # 停车问人只是白停一次（2026-10-03 run_1003c.log:91 就是这么停的：那条路
    # 的标签读成碎片「领」，优先表里查不到）。所以它排在最前面。
    # 「一条路」按 `reachable` 的**条数**数：同一个节点被箭头和青色线各报一次时
    # 会数成两条 —— 那种情况落到下面的老规矩（**只是可能多停一次车，不会走错**）。
    if len(reachable) == 1:
        return best, f"只有一条路可走（{best['kind']}）—— 直接走"

    if p >= UNKNOWN_PRIORITY:
        # 每层必走的出口（「深入」「首领」）：可前往的**全是**它们就直接走。
        if all(r["kind"] in LAYER_EXITS for r in reachable):
            names = "、".join(dict.fromkeys(r["kind"] for r in reachable))
            return best, f"可前往的全是每层必走的出口（{names}），走它"
        listed = "、".join(r["kind"] for r in reachable)
        return None, (f"可前往的这几处优先表里都没定过（{listed}）"
                      "—— 不猜，停下等人定")
    return best, f"按优先级走「{best['kind']}」(priority={p})"


