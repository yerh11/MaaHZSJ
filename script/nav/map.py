def node_kind(text):
    """把一段 OCR 文字归到节点词典；不是词典里的就返回 None（例如「强大」、层数 1~6）。

    判据是**完全相等**，不是子串。子串会把节点下方的描述行一起收进来：
    标题「战斗」+ 描述「·遭遇一场战斗」两条都含"战斗"，一个节点数成两个。
    描述行一律以「·」开头，先按这个挡一道，再要求整条与词条相等。

    刻意不做模糊匹配：屏幕边缘被截断的半个标签（实测见过「祭锻造间」）
    也返回 None 丢掉——错认一个节点的代价比漏认一个大。

    唯一的例外是**形近字**（见 CONFUSABLE）：整条原样查不到时，把单字换成
    形近的正字再查一遍**同一张表**。放宽的只有"单字替不替"这一层，
    "整条必须与词条完全相等"这条没动 —— 换完不在表里一样返回 None。
    """
    t = text.strip()
    if t.startswith("·"):  # 描述行，如「·遭遇一场战斗」「·发生甚么事了？」
        return None
    kind = _lookup(t)
    if kind is not None:
        return kind
    # 原样查不到 → 试试形近字修正（多数情况这里就返回 None，因为表里没这个字）
    fixed = _deconfuse(t)
    return _lookup(fixed) if fixed is not None else None


def _lookup(t):
    """整条与词典**完全相等**才算数；不在表里返回 None。"""
    for kind in NODE_KINDS:
        if t == kind:
            return kind
    return None


# **形近字修正表**：OCR 偶尔把某个字认成长得像的另一个字，整条词条就废了
# （差一个字 = 「优先表里都没定过」= 白停一次车）。查不到时才用：把读到的字
# 逐个换成右边的正字，再查一遍同一张表。
#
# 什么能进这张表（用户 2026-10-02 定的边界：「**只对形近字（字形相近、仅一笔之差）
# 放开**」）：
#   1. **亲眼见过的**——日志或截图里有那一行原文，不是"猜它可能读错"；
#   2. 两个字确实形近（共用偏旁、或只差一笔），OCR 有理由混；
#   3. 换完必须能落进词典 —— 落不进去的写法本来就会被丢掉，加了也没用。
#
# 为什么不做编辑距离/子串那类模糊匹配：本文件开头那个坑就是子串匹配把「战斗」
# 节点和它下面「·遭遇一场战斗」的描述数成了两个。边界一旦放开就收不回来，
# 而**错认一个节点的代价比漏认一个大**（引错路 vs 多问一句）。
CONFUSABLE = {
    "簧": "篝",   # 黯淡篝火→「黯淡簧火」（2026-10-02 实撞，run_1002q.log:13）
    # 大商店→「**人**商店」（2026-10-03 实撞，见 _ocr_band 第四眼那段）。
    # 那条标签压在底栏底下、字又小，OCR 反复把「大」的**那一横**丢掉 ——
    # 26 帧 × 5 个窗口共 130 次读数里，它是**这个字唯一**的错法；同样的错法
    # 也会落在「强**大**精英守卫」「强**大**锻造间」上，所以按字收、不按词收。
    # 三条边界都过：字形上「大」就是「人」加一横（一笔之差）；亲眼见过（这 130
    # 次读数）；换完落进词典（「大商店」在表里，另两个词条也受益）。
    # 反向不会误伤：词典里没有任何一条含「人」，所以这个替换**只有在真名确实是
    # 「大X」时才可能换出一个词条**。
    "人": "大",
    }


def _deconfuse(text):
    """按形近字表把字换回正字；一个都没换到（表里没这些字）就返回 None。"""
    fixed = "".join(CONFUSABLE.get(ch, ch) for ch in text)
    return fixed if fixed != text else None


def is_label_text(text):
    """这段 OCR 文字够格当节点标签吗。

    两道判据，都是实测踩坑换来的：

    1. **至少含一个汉字**。地形上那个蓝色雨云图标被 OCR 读成「6」，
       而它上方几十像素处恰有一枚 0.510 分的地形噪声"标记"（噪声稳定在
       0.51~0.53），几何窗口一配就成功，地图凭空多出一个叫「6」的可前往节点。
       真节点名全是汉字，纯数字/纯符号一律不是；右侧那列层数 1~6 也一并挡住。

    2. **不超过 LABEL_MAX_CHARS 个字**。这条是给**描述行**兜底的：描述行本应以
       「·」开头被挡掉，但那道闸**不可靠**——实测「·危险，但是无路可逃」在小 roi
       里被读成「危险，但是无路可」（「·」在 roi 外，前缀就没了）。
       真节点名最长才 5 个字（献祭锻造间），描述行动辄十字上下，字数能分开。
       ⚠️ **只管得住长描述**：2026-10-03 撞上「·向深处前进」只有 5 个字，
       字数分不开，补的是几何那条 —— 见 `is_description_row`。
       **万一将来真有超长节点名被丢掉，症状是"看到标记却配不上标签"、
       报成没有可前往节点——看得见、查得到；而放进一条描述行则是静默多出
       一个假节点，更难发现。所以宁可卡字数。**
    """
    return len(text) <= LABEL_MAX_CHARS and any("一" <= ch <= "鿿" for ch in text)


def is_description_row(lb, labels):
    """`lb` 是不是**另一条标签正下方那行小字**（节点的描述行）。

    判据、窗口怎么量的、以及那个「·」为什么不能靠，都写在 DESC_ROW_DY 那段。

    两条不能动的地方：
      · **词典认得出的一律返回 False** —— 「绝不丢节点」不让路。拿不准时留，
        不留就会凭空少一个节点、少一条路；多留最坏也只是停车问人。
      · **只看几何**：对 `labels` 里**其它**那条（谁在上、谁盖着谁），
        不看字长、不看颜色、不看那个点子。
    """
    if node_kind(lb["text"]) is not None:
        return False
    x, y, w, h = lb["box"]
    for other in labels:
        if other is lb:
            continue
        ox, oy, ow, oh = other["box"]
        if not DESC_ROW_DY[0] <= y - oy <= DESC_ROW_DY[1]:
            continue
        cover = min(x + w, ox + ow) - max(x, ox)
        if cover >= DESC_ROW_OVERLAP * min(w, ow):
            return True
    return False


def _pairs(mx, my, lb):
    """标签 lb 落在标记 (mx,my) 正下方那个窗口里吗；落在就返回 dy，否则 None。

    配对靠的是**几何关系**：整屏 OCR 的结果没有"这行属于哪个节点"的信息，
    唯一能用的就是"标记正下方那一小段里必然是它的标签"。
    """
    nx = lb["box"][0] + lb["box"][2] // 2
    ny = lb["box"][1] + lb["box"][3] // 2
    if abs(nx - mx) > MARKER_DX:
        return None
    dy = ny - my
    return dy if MARKER_DY[0] <= dy <= MARKER_DY[1] else None


def _ocr_roi(g, image, x0, y0, x1, y1):
    """在给定框里 OCR 一次，返回 [{"text", "box"}]（**全屏坐标**）。

    过滤（「·」开头的描述行、超长行、没汉字的）统一放在这里做，
    免得几个入口各写一份、日子久了走样。

    box 必须**把 roi 原点加回去**——和 Game.probe 一个道理，否则配对的
    几何校验量到的是裁剪后的小图坐标，永远对不上。
    框太小/贴着画面边缘时返回 []。
    """
    x0, y0 = max(0, x0), max(0, y0)
    x1, y1 = min(image.shape[1], x1), min(image.shape[0], y1)
    if x1 - x0 < 8 or y1 - y0 < 8:
        return []

    detail = g.tasker.post_recognition(
        "OCR", mpl.JOCR(), image[y0:y1, x0:x1]
    ).wait().get()
    # detail 可能是 None（引擎没收下任务，多半是控制器掉线）—— 先补 None 闸，
    # 再给掉线一次自救机会（Game._recover_engine）。同 core/auto.py 的 probe()。
    if detail is None:
        g._recover_engine()
        return []
    if not detail.node_id_list:
        return []
    nd = g.tasker.get_node_detail(detail.node_id_list[0])
    if nd is None or nd.recognition is None:
        return []

    out = []
    for r in (nd.recognition.all_results or []):
        text = r.text.strip()
        if not text or text.startswith("·") or not is_label_text(text):
            continue
        b = r.box
        out.append({"text": text, "box": (b[0] + x0, b[1] + y0, b[2], b[3])})
    return out


def _any_known(lbs):
    """这一把 OCR 结果里有没有**词典认得出**的（_ocr_band 的"第三眼"靠它决定
    还要不要接着换帧读）。"""
    return any(node_kind(lb["text"]) is not None for lb in lbs)


def _ocr_band(g, images, cx, cy):
    """标记正下方那一条单独 OCR，返回 [{"text", "box"}]（全屏坐标）。

    `images` 是**这一轮连拍的那几帧**（read_view 为箭头闪烁拍的，见 MARKER_FRAMES）；
    只喂一帧（存档回放那种）也能跑，只是没有第三眼。

    **为什么需要它**：整屏 OCR 会偶发漏标签。实测走到「首领」那一步，
    整屏把标题读成 'ww5x.'，标记找得到、标签配不上，于是整屏报"没有可前往
    节点"——看着就像地图坏了。而把标题那一小块单独喂进去是 1.00。
    整屏推理要在一张大图上跟背景抢小字，小 roi 没这个问题，而且快得多。

    **第二眼**（2026-10-02 夜）：上面这一条自己也读缺字 —— 见 TIGHT_* 那段。
    所以 band 里凡是**词典查不到**的结果，再围着它那一行开条紧条读一遍，结果
    追加在后面，由 read_view 那边"先认类、再比距离"挑。
    **紧条读回来还是碎片的，就再围一层**（2026-10-03，`TIGHT_LEVELS` 那段记着
    现场：一层只够读回 '首'+'领'，两块各自的紧条才是「首领」）。

    **第三眼：换帧**（2026-10-03）。同一处文字在**不同帧上的透明度不一样** ——
    用户当天看了那一屏，原话：「**只是字体一部分透明了**」。实测那个节点真名是
    「强大精英守卫」（词典里一直是对的，不是别名）：
        · 停车那次，band 和紧条读出来都是「大精英守卫」（「强」是透明的 → 丢了）
          → 词典查不到 → 停车「等待选路」（debug/run_1003b.log）；
        · 同一屏连读三次：一次读出完整的「强大精英守卫」，两次读缺。
    所以紧条也归不了类时，拿**同一个紧条**再去读 `images[1:]`，读到归得了类的
    就停。只在真出碎片时才跑 —— 正常一轮（读得全）一次都不多花 OCR 时间。
    和箭头那条路"多帧并集盖到亮相段"是同一个道理：**换帧比调参数管用**。

    **第四眼：削窗口**（2026-10-03）。上面三眼有个共同的**前提**——band 至少
    吐出过一块碎片：第二、三眼都是"围着碎片开紧条"。可是 band 自己一个字都没
    读出来的那种坏法（节点图标连光晕一起亮着，把那一行小字整个盖过去），三眼
    全都不跑，直接空手而归。所以补这一眼：band 一点东西都没吐、或吐的都归不了类
    时，把窗口**削窄削短到只剩标签那一行**、**一排放几个半宽**各读一次
    （见 LABEL_ROW_*：为什么是一组、为什么只留一个上沿，那边的注释写了实测）。
    结果并进 out，照样走后面的紧条与换帧。
    **只做加法**：band 读得出词典认得的东西时，它一次都不跑。

    一排放几个窗口是因为**没有哪个半宽常胜**（同 26 帧上单个窗口最好也只到 12/26），
    而一次小窗 OCR 只要 0.04s —— 五个全读也就 0.2s，比停车等人便宜三个数量级。
    挑法不是"先撞上谁算谁"，是**归得了类的最长那条**：窗口削窄的失手方式永远是
    **把边上的字切掉**（实测切掉「大」就剩「商店」，而那**本身就是词典里的另一类**，
    先撞上谁算谁会当场认错节点），所以"更长的完整读法"才更可能是真名。
    """
    image = images[0]
    out = _ocr_roi(g, image,
                   cx - LABEL_BAND_DX, cy + LABEL_BAND_DY[0],
                   cx + LABEL_BAND_DX, cy + LABEL_BAND_DY[1])
    if not _any_known(out):
        best = None
        for dx in LABEL_ROW_DXS:
            got = _ocr_roi(g, image,
                           cx - dx, cy + LABEL_ROW_DY[0],
                           cx + dx, cy + LABEL_ROW_DY[1])
            if not got or node_kind(got[0]["text"]) is None:
                continue
            if best is None or len(got[0]["text"]) > len(best["text"]):
                best = got[0]
        if best is not None:
            out.append(best)
    extra = []
    # 每一层待展开的碎片。第一层就是 band 的产出里归不了类的那些，
    # 第二层由 `_pairs` 挑（见 TIGHT_LEVELS 那段）。
    frontier = [lb for lb in out if node_kind(lb["text"]) is None]
    for _depth in range(TIGHT_LEVELS):
        nxt = []
        for lb in frontier:
            x, y, w, h = lb["box"]
            strip = (x - TIGHT_DX_L, y - TIGHT_DY, x + w + TIGHT_DX_R, y + h + TIGHT_DY)
            got = _ocr_roi(g, image, *strip)
            extra.extend(got)
            if not _any_known(got):
                # 换帧：同一处文字在各帧里透明掉的部分不同（见第三眼那段）。
                # 第一层照旧跑满 `images[1:]`；第二层只给 LABEL_FIX_FRAMES 帧——
                # 越往里越不该烧时间，而真出碎片的那一屏（battle_end.png）
                # 第二层**第一帧**就读全了。
                for other in (images[1:] if _depth == 0
                              else images[1:1 + LABEL_FIX_FRAMES]):
                    got = _ocr_roi(g, other, *strip)
                    extra.extend(got)
                    if _any_known(got):
                        break
            if not _any_known(got):
                nxt.extend(got)   # 这一层读回来还是碎片 → 下一层再围着它开条
        # 只留**配得上标记**的：离标记远的碎片补好了也只能让 nodes 好看一点，
        # 不值得为它多烧一遍帧序列。`_pairs` 用的就是配对那套几何。
        frontier = [lb for lb in nxt if _pairs(cx, cy, lb) is not None]
        if not frontier:
            break
    return out + extra


def _cyan_components(image):
    """屏幕上青色的"路径线"连通块，每块是一个 (N,2) 的 (y,x) 数组。

    判据只看颜色（见 CYAN_* 常量），不看形状——线的粗细、弧度、长短都会变。
    连通用 8 邻域自己扫，不引 scipy：图上青色像素就几百个，够快了。
    """
    b = image[:, :, 0].astype(int)
    g_ = image[:, :, 1].astype(int)
    r = image[:, :, 2].astype(int)
    mask = (b > CYAN_MIN_CHANNEL) & (g_ > CYAN_MIN_CHANNEL) & (b - r > CYAN_MIN_BR_DIFF)
    h, w = mask.shape

    seen = np.zeros_like(mask, dtype=bool)
    out = []
    for y0, x0 in zip(*np.nonzero(mask)):
        if seen[y0, x0]:
            continue
        q = deque([(y0, x0)])
        seen[y0, x0] = True
        pts = []
        while q:
            y, x = q.popleft()
            pts.append((y, x))
            for dy in (-1, 0, 1):
                for dx in (-1, 0, 1):
                    ny, nx = y + dy, x + dx
                    if 0 <= ny < h and 0 <= nx < w and mask[ny, nx] and not seen[ny, nx]:
                        seen[ny, nx] = True
                        q.append((ny, nx))
        if len(pts) >= CYAN_MIN_PIXELS:
            out.append(np.array(pts))
    return out


def _line_ends(pts):
    """一条线的两个端点。返回 [(x, y), (x, y)]。

    做法是**主成分**：把所有点投影到最长的那根轴上，投影最小/最大的两个点就是
    两端。比"取 y 最小/最大的点"稳——线可能是斜的、甚至接近水平。
    """
    p = pts[:, ::-1].astype(float)  # (N,2) 的 (y,x) → (x,y)
    d = p - p.mean(axis=0)
    # SVD 的第一根右奇异向量就是最长轴；不引 sklearn，一行就够
    _, _, vt = np.linalg.svd(d, full_matrices=False)
    t = d @ vt[0]
    return p[int(np.argmin(t))], p[int(np.argmax(t))]


def _ocr_window(g, image, cx, cy):
    """以 (cx,cy) 为中心的一个小窗口单独 OCR，返回 [{"text","box"}]（全屏坐标）。

    和 _ocr_band 一样是"整屏 OCR 会漏字"的兜底，区别是窗口**围着给定点**开，
    不是只往下开。box 同样要把 roi 原点加回去。
    """
    h, w = image.shape[:2]
    x0, x1 = max(0, int(cx - CYAN_OCR_DX)), min(w, int(cx + CYAN_OCR_DX))
    y0, y1 = max(0, int(cy - CYAN_OCR_DY)), min(h, int(cy + CYAN_OCR_DY))
    if x1 - x0 < 8 or y1 - y0 < 8:
        return []

    detail = g.tasker.post_recognition(
        "OCR", mpl.JOCR(), image[y0:y1, x0:x1]
    ).wait().get()
    # 同 _ocr_roi：detail 可能是 None（多半是控制器掉线），先补闸再自救。
    if detail is None:
        g._recover_engine()
        return []
    if not detail.node_id_list:
        return []
    nd = g.tasker.get_node_detail(detail.node_id_list[0])
    if nd is None or nd.recognition is None:
        return []

    out = []
    for r in (nd.recognition.all_results or []):
        text = r.text.strip()
        if not text or text.startswith("·") or not is_label_text(text):
            continue
        b = r.box
        out.append({"text": text, "box": (b[0] + x0, b[1] + y0, b[2], b[3])})
    return out


def _endpoint_density(pts, xy, r=CYAN_ARROW_R):
    """以 xy 为圆心、半径 r 内有多少青线像素——**箭头那头明显更密**。"""
    ys, xs = pts[:, 0], pts[:, 1]
    return int((((xs - xy[0]) ** 2 + (ys - xy[1]) ** 2) <= r * r).sum())


def _cyan_target(picked, pts, standing):
    """一条青线的两个端点里，**哪一头才是目标**（可前往的那个节点）。

    picked 是 [_line_ends] 那两个端点各自 OCR 出来的标签（可能某头是 None）。
    返回 (entry, how)；判不出方向就返回 (None, None)，由调用方丢掉这条线。
    判据的来龙去脉见上面 CYAN_* 常量那段。
    """
    alive = [e for e in picked if e is not None]
    if not alive:
        return None, None

    # 判据 1：调用方告诉我我站在哪 —— 剩下那头就是目标。精确。
    # kind 一律是词典里的原文（别名已废除），直接比字符串。
    if standing is not None and len(alive) == 2:
        stand = [i for i, e in enumerate(alive)
                 if (node_kind(e["text"]) or e["text"]) == standing]
        if len(stand) == 1:
            return alive[1 - stand[0]], "我站的"
        # 两头都是/都不是"我站的" —— 说明 standing 过期或标签认错了，落到判据 2

    # 判据 2：箭头那头更密
    if len(alive) == 2:
        d = [_endpoint_density(pts, e["xy"]) for e in alive]
        hi = 0 if d[0] >= d[1] else 1
        if d[hi] >= CYAN_ARROW_MIN and d[hi] >= CYAN_ARROW_RATIO * max(d[1 - hi], 1):
            return alive[hi], "箭头更密"
        return None, None

    # 判据 3：只读出一头。**这时密度得单独扛**——历史上两例（锻造间→事件、
    # 商店→篝火）都是只有目标那头读得出，可 map_see 那屏读得出的是**源**那头
    # 「起点」（密度 48）。光看"读出来了"分不开，得看它密不密。
    e = alive[0]
    if _endpoint_density(pts, e["xy"]) >= CYAN_ARROW_MIN:
        return e, "仅此一头+密"
    return None, None


def _cyan_reachable(g, image, standing=None):
    """只用**青色路径线**找可前往节点。返回 [{"kind","label","box","how"}]。

    **每条线只返回"目标"那一头**，源（当前节点）那头丢掉；判不出方向整条丢掉。
    为什么必须分方向、怎么分，见上面 CYAN_* 常量那段。

    短连通块（长边 < CYAN_LINE_MIN）直接跳过：那是箭头的青色描边，不是路径线。
    """
    found = []
    for pts in _cyan_components(image):
        ys, xs = pts[:, 0], pts[:, 1]
        if max(int(xs.max() - xs.min()), int(ys.max() - ys.min())) < CYAN_LINE_MIN:
            continue

        # 每个端点**最多留一条**标签：取框中心离端点最近的那个，免得一个窗口里
        # 读到的两三行文字把"两头"这件事搅成一堆。
        picked = []
        for x, y in _line_ends(pts):
            lbs = _ocr_window(g, image, x, y)
            if not lbs:
                picked.append(None)
                continue
            near = min(lbs, key=lambda lb: (lb["box"][0] + lb["box"][2] // 2 - x) ** 2
                       + (lb["box"][1] + lb["box"][3] // 2 - y) ** 2)
            picked.append({"xy": (x, y), "text": near["text"], "box": near["box"]})

        e, how = _cyan_target(picked, pts, standing)
        if e is None:
            continue
        found.append({"kind": node_kind(e["text"]) or e["text"],
                      "label": e["text"], "box": e["box"], "how": how})
    return found


def _head_lit(image, box):
    """箭尖那一块够不够亮 —— 专治"暗色同形物"的**第二道闸**。

    method 5（TM_CCOEFF_NORMED）是均值相减的算法，**天生抗光照**：地形上一块
    形状碰巧像箭头的暗斑，它给的分数和真箭头一样高（实测 0.669~0.727，比真箭头
    的呼吸低谷还高）。分数这个量救不了，得另找一个它看不见的。

    亮就是那个量：真箭头是**自发光**的青白色（在多数屏上 G 通道 95 分位 242~253），
    假命中的地形斑最高只到 203。**但这个 242 不是所有屏都成立** —— 2026-10-03 撞上
    一枚天生就暗的（30 帧最高 232，见上面 HEAD_MIN_SCORE 那段的补记），照 235 判
    它会整枚被关在外面。所以 HEAD_MIN_LIT 取 **220**：上距那枚的 232 有 12 点、
    下距地形斑的 203 有 17 点，两边都留得住。

    取 **95 分位**而不是最大值：最大值会被一个孤立的白像素骗过去（文字边缘、
    高光点都行），分位数要求"这一块整体偏亮"——箭头是实心的，正好吃这一条。
    """
    x, y, w, h = box
    patch = image[y:y + h, x:x + w]
    if patch.size == 0:          # 贴到画面外了
        return False
    return float(np.percentile(patch[:, :, 1], HEAD_LIT_PCT)) >= HEAD_MIN_LIT


def _marker_lit(image, box):
    """**整枚框**照箭尖那条闸判 —— 把框推到箭尖那一块再量。

    整枚框 40x47 里箭杆占了大半，直接量整块的 G 分位会被箭杆稀释；箭尖模板的
    框就是 (HEAD_DX, HEAD_DY) 处那个 24x23，所以推过去量的是**同一块像素**，
    两条路的判据才是同一个东西。

    为什么要给整枚也装这道闸（2026-10-02 补）：
    那天脚本第 5 次报「等待选路」停下 —— 地图上只有一条青线指着「战斗」，
    它却多报了一个「印记石」并照优先级点了过去，点了 20s 地图没关
    （存图 debug/screenshots/_park_1002ah.png，日志 debug/run_1002ah.log）。
    多出来的那枚是 (214,216,40,47) 一块**静止的灰地形斑**：连拍 10 帧分数
    恒为 0.6010、箭尖 p95G 恒为 201，而真箭头那 10 帧里冲到了 0.7610 /
    p95G **251** —— 同一批帧，亮闸（当时是 235，现在 220 也照样）两边分得
    干干净净，和箭尖那条路的结论一模一样。**整枚这条路此前只装了分数闸，
    假命中就是从这儿漏进来的。**
    """
    return _head_lit(image, (box[0] + HEAD_DX, box[1] + HEAD_DY, HEAD_W, HEAD_H))


def _match_frame(g, img):
    """一整帧上跑三路模板匹配，返回这一帧认出来的 [(score, box), ...]。

    **只匹配、不归并**（归并在 _merge_found 里）。拆开是为了连拍时能**边拍边匹配**
    —— 匹配必须跑、采样间隔也必须留，从前两段串着走，现在让匹配去填采样的空档，
    见 _burst。

    三个来源，**同一个坐标系**：整枚 `可前往标记`；只认下半截的 `可前往箭尖`
    （尾巴被挡时用，见 HEAD_MIN_SCORE 那段）；只认上半截的 `可前往箭尾`
    （箭尖被图标光晕吃掉时用，见 TAIL_MIN_SCORE 那段）。两条替补路的命中框都先按
    各自的偏移**推回整枚的框**再加进来，所以归并、配对、报出来的框，三条路共用一套。

    整枚那一路**不重设框的大小**（就用匹配返回的那个），和从前逐字一致；只有两条
    替补路要按 MARKER_SIZE 推回整枚的大小 —— 它们认的本就是整枚的一截。
    """
    out = []
    for node, min_score, lit, dx, dy in (
            (可前往标记, MARKER_MIN_SCORE, _marker_lit, 0, 0),
            (可前往箭尖, HEAD_MIN_SCORE, _head_lit, HEAD_DX, HEAD_DY),
            (可前往箭尾, TAIL_MIN_SCORE, _head_lit, TAIL_DX, TAIL_DY)):
        # all_results **不受 threshold 过滤**（实测 0.5x 的结果也会返回），自己筛。
        reco = g.probe(node, img)
        for r in (reco.all_results or []) if reco else []:
            if r.score < min_score:
                continue
            box = tuple(r.box)
            # 亮度闸一律量**命中的那一块本身**：整枚量整枚，替补路量它认的那一截。
            # 箭尾那路尤其不能拿箭尖当判据 —— 它的前提恰恰是"箭尖看不清"，
            # 拿看不清的那块当判据等于拿已知不可靠的东西当证据。
            if not lit(img, box):
                continue          # 暗色同形物：分数够了，亮度不够（见 _marker_lit）
            if dx or dy:
                box = (box[0] - dx, box[1] - dy, MARKER_SIZE[0], MARKER_SIZE[1])
            out.append((r.score, box))
    return out


def _merge_found(frames):
    """把逐帧的命中并成一张表（取并集）。返回 [(score, box), ...]，按位置排序。

    入参 frames 是 [[(score, box), ...], ...] —— 每一帧的 _match_frame 结果。

    归并按**中心距离贪心聚类**，不用网格：网格的边界会把同一枚箭头劈成两条——
    实测就撞上过，同一枚 (511,430) 的标记被记成 0.838 和 0.784 两个可前往节点，
    直接让有向图多出一条不存在的边。真标记之间隔着整个节点，间距远大于阈值，
    所以聚类不会把两枚不同的箭头并成一个。

    **三条路互不替代，也不互相压制**：都是"只做加法"，同一位置取分最高的那次
    （add 里的贪心聚类）。多认出一枚不会顶掉另一枚 —— 一个可前往节点都丢不起。

    ⚠️ 贪心聚类**与喂进来的顺序有关**，而 _burst 改了"什么时候匹配"、没改
    "按什么顺序喂"（仍然是按帧、帧内按三条路的次序），所以这里的顺序和从前逐字一致。
    """
    merged = []  # [(score, box)]

    def add(score, box):
        cx, cy = box[0] + box[2] // 2, box[1] + box[3] // 2
        for i, (s, b) in enumerate(merged):
            bx, by = b[0] + b[2] // 2, b[1] + b[3] // 2
            if abs(cx - bx) <= MARKER_MERGE_DIST and abs(cy - by) <= MARKER_MERGE_DIST:
                if score > s:  # 同一个位置留分数最高的那次
                    merged[i] = (score, box)
                return
        merged.append((score, box))

    for hits in frames:
        for score, box in hits:
            add(score, box)
    return sorted(merged, key=lambda sb: (sb[1][1], sb[1][0]))


def _merge_markers(g, images):
    """手上只有几张**现成帧**时的那条路：逐帧匹配再归并（见 _merge_found）。

    自己连拍的那条走 _burst（边拍边匹配，省掉一整段串行的匹配时间）。
    """
    return _merge_found([_match_frame(g, img) for img in images])


def _burst(g):
    """连拍 MARKER_FRAMES 帧，**边拍边匹配**。返回 (images, frames)。

    2026-10-03 用户说「地图识别和扫描有点慢」之后改的。匹配必须跑、采样间隔也必须
    留（箭头会呼吸，样本得散在时间轴上），从前是"先拍完 24 帧（4.4s）再跑 12 遍
    三路匹配（2.7s）"两段串着走 —— 后一段整个是排队等的。现在把匹配塞进采样的
    空档里：三路约 0.23s、帧距 0.18s，一拍只顺延约 0.05s，24 拍多约 0.6s，
    而那一整段匹配时间被吃掉了。

    跨度**只增不减**（4.37s → 约 5.0s），所以"盖住暗段"那条余量反而更宽；
    帧数、抽帧比例、三路判据一个字没动（见 MARKER_FRAMES / MARKER_MATCH_EVERY）。

    抽帧仍是**每 MARKER_MATCH_EVERY 帧匹配一张**（i 从 0 起，所以匹配的是
    0,2,4,… —— 和从前 `images[::MARKER_MATCH_EVERY]` 逐个对得上）。
    """
    images, frames = [], []
    nxt = time.perf_counter()
    for i in range(MARKER_FRAMES):
        images.append(g.capture())
        if i % MARKER_MATCH_EVERY == 0:
            frames.append(_match_frame(g, images[-1]))
        # 睡到**这一拍的时间点**（不是"睡满一个帧距"）—— 匹配花掉的那部分不重复睡，
        # 采样间隔因此保持约 0.18s，不会变成 0.18 + 匹配。
        nxt += MARKER_FRAME_GAP
        rest = nxt - time.perf_counter()
        if rest > 0:
            time.sleep(rest)
    return images, frames


def _near(box_a, box_b, dist=25):
    """两个框的中心横纵差都在 dist 以内（方形判定，够用且好读）。

    默认 25 是 goto 里"同一视图内重认同一个节点"的容差；标签去重另传小值。
    """
    ax, ay = box_a[0] + box_a[2] // 2, box_a[1] + box_a[3] // 2
    bx, by = box_b[0] + box_b[2] // 2, box_b[1] + box_b[3] // 2
    return abs(ax - bx) <= dist and abs(ay - by) <= dist


def read_view(g, image=None, standing=None, markers=None):
    """读一次地图视图，返回：

        {
          "nodes":     [{"kind", "box"}],                       全部节点
          "markers":   [(score, box)],                          可前往标记
          "reachable": [{"kind", "box", "marker", "how"}],      配对成功的可前往节点
        }

    box 一律是全屏坐标 (x, y, w, h)——Game.probe 已经把 roi 原点加回去了。

    image 传 None 时会**连拍 MARKER_FRAMES 帧**用于标记取并集（防闪烁）；
    调用方已经截好图传来时，就只用那一帧。

    standing 是**当前站的节点的 kind**（"起点"/"战斗"/…），可选。青色那条路
    靠它精确分方向；不传就用箭头密度猜，见 _cyan_target。

    markers 传上一轮读出来的标记表时，**跳过连拍**：连拍只为标记取并集（防箭头
    呼吸），而地图是静的——同一屏重读时标记的位置一颗都不会挪，会变的只有**标签
    OCR 这一帧读得全不全**。所以补读字不必再跑一遍 4 秒的连拍。
    谁在用：map_view 的 READ_TRIES（它的重读本来就是为标签漏读加的），见那里。

    代价说实话：这么调时手上只有一帧，凡是**靠"换一帧再读"补字**的兜底
    （整屏标签的换帧补读、_ocr_band 的第三眼）都无帧可用。换来的是每次重读
    约 10s → 约 0.5s，而那两个兜底在**第一次**读的时候已经跑过一遍了。
    """
    if image is None and markers is None:
        # 自己连拍：边拍边匹配，见 _burst。匹配这一遍是白搭在采样空档里的。
        images, matched = _burst(g)
    elif image is None:
        # 只补读标签（markers 是上一轮读出来的）：连拍不用跑，见上面那一段。
        images, matched = [g.capture()], None
    else:
        images, matched = [image], None

    # 标记在**标签之前**算好：换帧补读要用它决定"先修哪个标签"（离标记近的先修）。
    # 它不依赖标签（只认箭头形状），挪上来不影响任何判据。
    if markers is None:
        markers = (_merge_found(matched) if matched is not None
                   else _merge_markers(g, images[::MARKER_MATCH_EVERY]))

    # OCR 出**全部**文字，先不过词典——配对要用它。
    #
    # **只拿词典里的词去配对是错的**，实测栽过两次：地图上会出现没收录的写法
    # （「深入」，以及后来遇到的「双生印记」），那样标记找得到、标签配不上，
    # 整屏就报"没有可前往节点"，看着像地图坏了。
    # 判据是**几何关系**（标记正下方那一小段里有文字），词典只负责给它归个类。
    # 以「·」开头的描述行（如「·同时附加2个印记」）不是标签，先剔掉；
    # 不含汉字的（地形图标被读成「6」这种）也不是，见 is_label_text。
    labels = []
    reco = g.probe(地图节点文字, images[0])
    for r in (reco.all_results or []) if reco else []:
        text = r.text.strip()
        if not text or text.startswith("·") or not is_label_text(text):
            continue
        box = tuple(r.box)
        # 同一段文字**可能被返回两次**，两个框只差几个像素（实测「祝福祭坛」
        # 同时出现在 (859,568) 和 (860,562)），节点数就这么被虚报了一个。
        # 同一个节点只会有一个标签，位置这么近的直接并成一个。
        nx, ny = box[0] + box[2] // 2, box[1] + box[3] // 2
        if any(
            abs(nx - (lb["box"][0] + lb["box"][2] // 2)) <= LABEL_DUP_DIST
            and abs(ny - (lb["box"][1] + lb["box"][3] // 2)) <= LABEL_DUP_DIST
            for lb in labels
        ):
            continue
        labels.append({"text": text, "box": box})

    # **节点名正下方那行小字不是节点**（「·向深处前进」这种），剔掉。
    # 挡它的三道闸里，「·」前缀会被 OCR 读丢、字长只管得住长描述，
    # 剩下几何这一道，见 is_description_row。剔在这里 = 后面的配对、
    # `nodes` 列表、以及 band 兜底（下面那道）全都看不到它。
    kept = []
    for lb in labels:
        if is_description_row(lb, labels):
            continue
        kept.append(lb)
    labels = kept

    # **读缺字的标签，换帧再读一遍**（2026-10-03）。
    #
    # 用户当天看着那一屏给的判据：「**只是字体一部分透明了**」—— 同一处文字在
    # 连拍的那十帧里，透明的是哪一部分并不相同，所以有的帧读得全、有的帧读缺。
    # 那个节点真名是「强大精英守卫」（词典里一直是对的，不是别名）：
    #   · 停车那次读成「大精英守卫」（「强」透明 → 丢了）→ 词典查不到 →
    #     停车「等待选路」（debug/run_1003b.log）；
    #   · 同一屏连读三次：一次读出完整的「强大精英守卫」，两次读缺。
    # 所以只对**词典查不到**的标签换帧补读（正常地图一次都不跑），读到归得了类
    # 的就停。**换帧而不是调参数** —— 和箭头那条路"多帧并集盖到亮相段"一个道理。
    #
    # 修在**这里**而不是只修配对那条兜底路：没有标记可配的时候（箭头正处在
    # 闪烁的暗相，一屏 0 枚 —— 实测常见）配对循环整个不跑，那条兜底根本没机会。
    #
    # ⚠️ **2026-10-03 加"先修谁"和"修多少"**（用户当天说「地图识别和扫描有点慢」）。
    # 上面那句"正常地图一次都不跑"**是错的**：profiler 一量，这一屏（battle_map.png）
    # 有 7 个词典外的标签，每个跑满 4 帧 = 28 次小窗 OCR ≈ **2.0s**，而它们
    # **一个都补不回来**——整屏 OCR 吐的是碎片（'区' '愁' '永' '游'，还有顶栏那行
    # '神智 0/12'），拿它开的小窗读回来还是那个碎片。真正的用例（「大精英守卫」←
    # 「强大精英守卫」）只有**一个**标签、4 次 OCR 就够，却被这堆碎片陪着一起烧。
    # 两处都只动"什么时候去修"，判据一个字没改：
    #   · **离标记近的先修**——补好了才可能变成可前往节点，这是唯一值得修的那类；
    #   · 附近一枚标记都没有的那一堆**共用一份小预算**（离标记远的补好了也只能让
    #     nodes 好看一点）。预算花完就停，剩下的标签原样留着——它们仍然会被
    #     "绝不丢"那条路按原文收进 nodes。
    def _fix_rank(lb):
        """0 = 落在某枚标记的配对窗口里（值得修），1 = 不在（垫底）。"""
        for _score, mbox in markers:
            mx, my = mbox[0] + mbox[2] // 2, mbox[1] + mbox[3] // 2
            if _pairs(mx, my, lb) is not None:
                return 0
        return 1

    tail_budget = LABEL_FIX_TAIL_BUDGET
    for lb in sorted((l for l in labels if node_kind(l["text"]) is None),
                     key=_fix_rank):   # sorted 是稳定的：同档内保持 OCR 原来的次序
        rank = _fix_rank(lb)
        if rank and tail_budget <= 0:
            continue                  # 垫底那一档预算花完了，原样留着
        x, y, w, h = lb["box"]
        strip = (x - TIGHT_DX_L, y - TIGHT_DY, x + w + TIGHT_DX_R, y + h + TIGHT_DY)
        for other in images[1:1 + LABEL_FIX_FRAMES]:
            if rank and tail_budget <= 0:
                break
            if rank:
                tail_budget -= 1
            known = [e for e in _ocr_roi(g, other, *strip)
                     if node_kind(e["text"]) is not None]
            if known:
                lb["text"], lb["box"] = known[0]["text"], known[0]["box"]
                break

    # nodes 只收词典认得出的（列"这张图有什么"、挑拖动落点用）；
    # 配对成功但词典不认识的，下面再补进去。
    nodes = []
    for lb in labels:
        kind = node_kind(lb["text"])
        if kind:
            # label 是屏幕上**原文**，kind 是词典里那一条。留着原文是为了报出来时
            # 不丢信息 —— 别名废除后两者通常相同，**只有形近字修正过时不同**
            # （屏幕上读成「黯淡簧火」，词典里那一条是「黯淡篝火」）。
            nodes.append({"kind": kind, "label": lb["text"], "box": lb["box"]})

    # markers 已经在上面（标签之前）算好了 —— 换帧补读要用它排优先级。

    reachable = []
    for _score, mbox in markers:
        mx, my = mbox[0] + mbox[2] // 2, mbox[1] + mbox[3] // 2

        # 先拿整屏结果配（一次 OCR 覆盖全屏，便宜且通常够用），
        # 取窗口里离标记最近的那条。
        best, best_dy = None, None
        for lb in labels:  # ← 用全部文字配，不是用 nodes
            dy = _pairs(mx, my, lb)
            if dy is not None and (best_dy is None or dy < best_dy):
                best, best_dy = lb, dy

        # 整屏 OCR 在这一步有**两种**坏法，两种都要补一次小 roi 再试：
        #
        #   1. **整条漏读**（best is None）——实测「首领」被读成 'ww5x.'；
        #   2. **配上了、却读成词典外的碎片**（node_kind 认不出）——2026-10-02
        #      实测「深入」在整屏里被读成「深）」（score 0.7345，检测框还比真
        #      标签窄 8px：34 宽 vs 42）。它一路被当成"没见过的写法"往上走，
        #      优先表里查不到 → 停车「等待选路」。而同一帧把标记正下方那一小条
        #      单独喂进去就是「深入」**1.0000**。
        #      ——模型没瞎，是**整屏上下文**把它读坏的：小窗没这个问题。
        #
        # 只在兜底路径上跑，所以正常一轮不会多花 OCR 时间。
        if best is None or node_kind(best["text"]) is None:
            # 挑选用**先认类、再比距离**（从前是纯比 dy），因为纯比距离在两个
            # 地方会挑错，两处都实测过：
            #   · 「深）」dy=95、「深入」dy=96 只差 1px —— best 读成碎片时，
            #     按距离换会换不掉；
            #   · band 自己先吐碎片、紧条再吐完整的（「领」(647,226) vs
            #     「首领」），两框是同一条线，dy 几乎一样，同样挑不回来。
            # 所以"归得了类"当第一关键字，距离只在同一档里比。
            fallback, fallback_dy = None, None   # 归得了类的那一档
            raw, raw_dy = None, None             # 归不了类的，垫底用
            for lb in _ocr_band(g, images, mx, my):
                # band 是**另一条路**，会把这行小字再捞回来——实测真标记那处
                # (882,215) 的 band 读回来就是 '向深处前进'（点又丢了，框
                # (850,338,87,21)）。所以上面那道剔不能只管标签表，这里再剔一次。
                if is_description_row(lb, labels):
                    continue
                dy = _pairs(mx, my, lb)
                if dy is None:
                    continue
                if node_kind(lb["text"]) is None:
                    if raw_dy is None or dy < raw_dy:
                        raw, raw_dy = lb, dy
                elif fallback_dy is None or dy < fallback_dy:
                    fallback, fallback_dy = lb, dy
            # raw **只给"整屏一条都没配上"垫底**（best is None）；best 已经是
            # 碎片时不换 —— 拿一个碎片换掉另一个碎片等于没兜底。这句顺带挡住
            # 那行描述：「·向深处前进」在兜底窗口里因为裁掉了「·」会以
            # 「向深处前进」活下来（dy=116，也在配对窗口内），但它归不了类，
            # 只有在 best is None 时才会被拿来垫底——而垫底是为了**绝不丢节点**
            # （词典外的写法下面会按原文补进 nodes，丢一个真实可前往的节点
            # 等于把地图上一整条路抹掉）。
            if fallback is not None:
                best, best_dy = fallback, fallback_dy
            elif best is None and raw is not None:
                best, best_dy = raw, raw_dy

        if best is None:
            continue

        # 词典认得就归类，认不得就用**原文**当类型——绝不丢。
        # 丢一个真实可前往的节点，等于把地图上一整条路抹掉。
        kind = node_kind(best["text"]) or best["text"]
        # 用 _near 比，**不能用框完全相等**：best 可能来自 _ocr_band 的小 roi，
        # 同一段文字在整屏 OCR 和小 roi 里的框能差 7px（实测「游艺」两个框
        # (1050,632) 与 (1050,625)），完全相等挡不住，地图上就多出一个同名节点。
        # ⚠️ 这两道闸问的是**两件不同的事**，别合并（2026-10-05 修错过一次，见下）。
        #
        # 第一道（`nodes`）：这个标签是不是**已经**在 `nodes` 里了 —— 上面那轮
        # `for lb in labels` 早把词典认得出的标签整体登记过一遍，配对的这枚 `best`
        # 十有八九就是其中那一条（同一个 dict，框一模一样）。所以这道闸挡的是
        # "**同一个标签登记两遍**"，正常一轮里它**天天为真**。
        #
        # 第二道（`reachable`）：这一**配**是不是跟前面某一配指向同一处（2026-10-05 加）。
        # `reachable` 是**按标记**记的账，一道配一笔；两枚标记挨着（连拍的并集把同一枚
        # 箭头登记成 16px 的两枚，刚过 MARKER_MERGE_DIST=15 那道聚类）时，会各自往
        # `reachable` 里写一笔，同一格就**列两遍**：日志看着像那儿有两个节点，两个写法
        # 要是落在不同的号上，挑路会被带歪（run_1004_1330.log:11203-11204 就是一次：
        # 同一格列成「强大锻造间」(50) 和「强大锻造」(1) 两条，点差 7px）。半径与
        # `nodes` 那道**同一把尺**（LABEL_DUP_DIST）—— 地图上节点之间隔着整个身位，
        # 标签框挨到 12px 以内的只可能是**同一处**。
        # 顺带的好处：重复少了，`len(reachable) == 1` 更常成立，那条"只有一条路就走"
        # 的保底少被虚报的条数骗掉（它按**条数**数，见 pick_target 那条注）——
        # 单节点那格从前数成 2 条时它不生效，只能去比优先级，认不出号就得停车。
        #
        # ⚠️ **第一道闸不许管 `reachable`**：把 `reachable.append` 也塞进 `if` 里
        # （当天第一版就是这么写的）会让**正常一轮一个可前往都不剩** —— 第一枚标记
        # 的 `best` 必然已经在 `nodes` 里，一 `continue` 连账都不记。当场被
        # `debug/map.py check` 逮住（`op/11_see.png` 期望 2 实得 0、`op/10_see.png`
        # 期望 2 实得 1、`_park_1002ai_map.png` 期望 1 实得 0、`_map_forerunner.png`
        # 期望 1 实得 0；HEAD 版四条全过）。
        if any(_near(r["box"], best["box"], LABEL_DUP_DIST) for r in reachable):
            continue
        if not any(_near(n["box"], best["box"], LABEL_DUP_DIST) for n in nodes):
            nodes.append({"kind": kind, "label": best["text"], "box": best["box"]})
        reachable.append(
            {"kind": kind, "label": best["text"], "box": best["box"], "marker": mbox}
        )

    # 用**青色路径线**给箭头补漏（见 CYAN_* 常量那段注释）。
    #
    # 从前这里是 `if not reachable:`——一枚标记都没配上才兜底，是"全有或全无"。
    # 2026-10-01 就栽在这个"全"上：连拍取并集只凑到了「精英战斗」一枚并配上了
    # 标签，兜底于是**整体不跑**；而同一屏上明明还有一条 1494 像素的青色长线
    # 指向「游艺」，被整条漏掉——用户当场说"有两个节点可以走"，脚本只报了一个。
    # 现在的规矩是**每次跑、只做加法**：它排在箭头后面，只往 nodes/reachable 里
    # 追加没见过的标签，箭头已经认出来的一点都不会被动。
    #
    # 这里拿到的已经**只剩每条线的目标那头**（源那头由 _cyan_target 判掉），
    # 所以下面不会再出现"把当前节点标成可前往自己"那种自环。
    for raw in _cyan_reachable(g, images[0], standing):
        text = raw["label"]

        # 先**认字**，再谈别的。青色那条路是"小窗口 OCR"，读回来的十有八九是
        # 碎片，直接收会把地图搅乱——实测放过「精英占」（「精英战斗」被切掉一半）
        # 和「遭遇受到祝福」（描述行少了「·」前缀的残段），地图上凭空多两个节点。
        # 只收两种：
        #   1) **词典认得出**的（游艺/战斗/商店…），这是正经节点名；
        #   2) 和本轮**全屏 OCR 读到的某条标签对得上**（一字不差，或一方是另一方
        #      的子串——「战斗」对上「精英战斗」这种截断），且位置也挨着。
        #      这种是"这个节点本来就看见了，青色线只是告诉我们它可前往"。
        # 都不满足的丢掉。代价是：**词典不认识、全屏 OCR 又漏了**的节点名，
        # 青色这条路就报不出来——认它还得靠箭头那条路（那边有 _ocr_band 兜底）。
        if node_kind(text):
            r = raw
        else:
            same = None
            for lb in labels:
                if len(text) < 2:
                    break
                if text == lb["text"] or text in lb["text"] or lb["text"] in text:
                    if _near(raw["box"], lb["box"], CYAN_DUP_DIST):
                        same = lb
                        break
            if same is None:
                continue
            r = {"kind": node_kind(same["text"]) or same["text"],
                 "label": same["text"], "box": same["box"], "how": raw["how"]}

        # 归并：同一个节点在 nodes 里就**把它标成可前往**，不在才新增。
        #
        # 从前这里写的是"挨着谁就 continue"，两个毛病：
        #   · 标签已经被全屏 OCR 读到的节点（比如「游艺」），青色线认出来之后
        #     既不会新增、也**不会被标成可前往**——"看见"和"能去"两件事被搅成一件；
        #   · 判定半径 12px 挡不住小窗口 OCR 的偏移（见 CYAN_DUP_DIST）。
        hit = next((n for n in nodes if _near(n["box"], r["box"], CYAN_DUP_DIST)), None)
        if hit is not None:
            if not any(_near(x["box"], hit["box"], CYAN_DUP_DIST) for x in reachable):
                reachable.append({"kind": hit["kind"], "label": hit.get("label"),
                                  "box": hit["box"], "marker": None, "how": raw["how"]})
            continue
        nodes.append(r)
        reachable.append(dict(r, marker=None))

    # **必须显式排序**：有向图里"第 i 个可前往节点"就是节点身份，
    # 而 all_results 的返回顺序没有保证。按标签自上而下、自左而右排，
    # 同一视图多次读出来的顺序就一致了。
    key = lambda o: (o["box"][1], o["box"][0])
    nodes.sort(key=key)
    reachable.sort(key=key)
    return {"nodes": nodes, "markers": markers, "reachable": reachable}


def icon_center(box):
    """标签框 → 该节点的图标中心（点它才是走动）。"""
    return box[0] + box[2] // 2, box[1] + box[3] // 2 + ICON_DY


def _pick_anchor(nodes):
    """从候选落点里挑一个离所有已知节点最远的，避免拖动起止点压在节点上被当成点击。"""
    if not nodes:
        return DRAG_ANCHORS[0]
    best, best_gap = DRAG_ANCHORS[0], -1
    for ax, ay in DRAG_ANCHORS:
        gap = min(
            max(abs(ax - (n["box"][0] + n["box"][2] // 2)),
                abs(ay - (n["box"][1] + n["box"][3] // 2)))
            for n in nodes
        )
        if gap > best_gap:
            best, best_gap = (ax, ay), gap
    return best


def pan(g, dx, dy, steps=14):
    """把地图画面拖动 (dx, dy)。

    用 touch_down → 多次 touch_move → touch_up，**不用 post_swipe**：
    这个项目在难度轮盘上已经栽过一次（一把梭的滑动会被游戏吞）。
    起止点自动避开已知节点，免得手指抬起那一下被当成点击。
    """
    image = g.capture()
    nodes = read_view(g, image)["nodes"]
    x0, y0 = _pick_anchor(nodes)
    g.controller.post_touch_down(x0, y0).wait()
    for i in range(1, steps + 1):
        g.controller.post_touch_move(x0 + dx * i // steps, y0 + dy * i // steps).wait()
        time.sleep(0.02)
    g.controller.post_touch_up().wait()


# ---------------- 贴着下沿的节点：拖地图让它露出来 ----------------
#
# 地图显示区的下沿。底栏（金币/生命/版本号）是一条暗色实心横条**压在画面最上面**，
# 落到它下面的标签就看不见了 —— 用户 2026-10-03 看着那枚「大商店」说的：
# 「字体在地图显示区域外面」。
#
# 量法（离线，debug/screenshots/_now.png 逐行平均亮度）：
#     y=600..662 稳定在 85~94（地图画面）
#     y=664 掉到 51，y=666 弹回 92（横条上沿那道高光），y=670 之后稳定 38~45（底栏本体）
# 取下沿 662：高光那行不算进地图区，宁可多拖一次也别少拖。
# `MAP_BOTTOM` 与 `BOTTOM_BAND`（标记中心离下沿多近算贴着）已搬进 `shared/coords.py`。


def bottom_dangling(view):
    """贴着地图区下沿、这一轮**读不到标签**的地方 —— 返回 [(标记框, 说明)]。

    两种情况都算：
      · 可前往节点的标签框底边越过了下沿 —— 字读出来了，可那是从底栏底下抠出来的；
      · 下沿那一条带有标记、却没配上任何标签 —— 标记找得到，字压根没读出来。
    成因只有一个：**标签落在底栏下面**。

    用户 2026-10-03 定的做法是**拖地图让它露出来**，不是在那层半透明膜上硬读。
    硬读的代价有据可查：_ocr_band 第四眼确实抠得出「大商店」（削到 y+95..145、
    一排五个半宽），可下一步 goto 还要**再读一次**确认，而那一枚箭头 88% 的帧
    是暗的 —— 同一枚标记要抽中两次（debug/run_1003b.log 就是这么停的：
    这一轮读出「大商店」，goto 复验两次都没抽中，自己把自己拦下）。
    """
    out = []
    for n in view["reachable"]:
        x, y, w, h = n["box"]
        if y + h > MAP_BOTTOM:
            out.append((n.get("marker") or n["box"],
                        f"「{n['kind']}」的标签越过下沿 {y + h - MAP_BOTTOM}px"))
    paired = [n["marker"] for n in view["reachable"] if n.get("marker")]
    for _score, mbox in view["markers"]:
        if mbox[1] + mbox[3] // 2 < MAP_BOTTOM - BOTTOM_BAND:
            continue
        if any(_near(mbox, p, LABEL_DUP_DIST) for p in paired):
            continue
        out.append((mbox, f"({mbox[0]},{mbox[1]}) 那枚标记没配上标签"))
    return out


def pan_to_reveal(g, marker_box, scale=0.5):
    """把地图往**那枚标记 → 屏幕中心**的方向拖，连它下面的标签一起拖进可视区。

    方向是用户 2026-10-03 给的：「箭头 → 屏幕中心」（先说了「屏幕中心向箭头」，
    当场纠正为「说反了」）。实测也站这一边 —— 画面**跟着手指走**：往箭头方向拖
    （下）那一屏整体下移，「大商店」被推出画面、连标记都读不到了；反着拖才把它
    抬上来。

    只拖半个向量（scale）：整段拖会把节点顶到画面正中，惯性一冲容易过；半个就够
    让标签从下沿底下露出来，露不够调用方下一轮再拖一次（有次数上限）。
    """
    h, w = g.capture().shape[:2]
    cx, cy = w // 2, h // 2
    mx, my = marker_box[0] + marker_box[2] // 2, marker_box[1] + marker_box[3] // 2
    pan(g, int((cx - mx) * scale), int((cy - my) * scale))


