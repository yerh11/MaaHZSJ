# 算的 —— 定点扫等于替每一帧都点在了同一处，自然齐刷刷读对；改成**每帧按它自己
# 那枚标记的中心**开窗，同一对数立刻时对时错。
# 真实的行为是这样（26 帧 × 5 个半宽 = 130 次读数，全部落在 y 上沿 95 那一行）：
#   · 5 个半宽**没有一个是常胜的**：54 读对 8/26、56 读对 6/26、58 读对 12/26、
#     60 读对 10/26、62 读对 3/26 —— 同一帧往往只有一两个窗口读得对，而且
#     **是哪一两个还随帧换**（glow 呼吸相位一变，同一个窗口的读数就变）。
#   · 读错永远是**单字混**：大↔人、商↔尚（「大商店」→「人商店」「大尚店」
#     「人尚店」），从没出现过整条乱码。
#   · 窗口**再往外放就崩**：x±64 起 26 帧一次都没读对过（全在 人商店/人尚店 一带）。
# 所以这里放一**组**半宽，读一网、挑一条：见 _ocr_band 的第四眼（挑法：
# **归得了类的最长那条**）。上沿只留 95 一个值：抬高 5px（y=90）当场读成
# 「大店」「A店」——把图标底边带回来了；压低到 97 以上则切掉「大」的顶横，
# 26 帧里读出来的一律是「人商店」。**95 这个数是硬的，左右那几个不是。**
#
# ⚠️ 这组窗口只装得下约 5 个字（±54 = 108px~±62 = 124px；真实标签 110px）。
# 最长的节点名「强大精英守卫」实测 139px，**从每一个窗口里都露出去**。
