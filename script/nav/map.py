# 免得下次有人查"为什么没拖动"时读到的是这份不跑的实现。拖动原语 pan() 仍在下面。


def goto(g, node, timeout=20.0):
    """点某个节点走过去。node 是 read_view 返回的那种 {"kind","box"}。

    只对**当前视图内**的节点有效——先重新截一帧确认它还在原地，再点。
    点完等地图消失（地点界面出现 / 地图锚点消失）。

    返回 **(是否走成功, 说明)**。说明是给人看的：从前这里只回 bool，
    调用方只能印一句「点了，但地图没关掉」，而**没认出节点根本没点**也走这条
    分支——实测 2026-10-01 走 n27 就是这么被误导的：真因是这一眼把标签
    「事件」读成了「生基」（地图标签是花体，OCR 本来就飘），压根没发点击。

    **身份判据是位置，不是 kind。** 从前这里要求 `n["kind"] == node["kind"]`，
    等于拿最飘的那个信号（标签 OCR）去当门禁：同一屏前后两次 read_view，
    一次读出「事件」、一次读出「生基」，行走就被静默拦下。而被点的是**那个位置**——
    地图上两个节点近到 25px 以内的可能性不存在，位置比文字硬得多。
    kind 对不上只**警告**，不拦：那大概率是 OCR 飘了，不是走错了。
    """
    image = g.capture()
    fresh = read_view(g, image)
    hit = next((n for n in fresh["nodes"] if _near(n["box"], node["box"])), None)

    # 单帧没找到 → **多帧再读一次**，别就此放弃。
    #
    # 词典认得出的节点（战斗/印记石/篝火…）单帧也在 nodes 里（标签自己就够），
    # 这里兜的是**词典不认识、只能靠"标记配上标签"进 nodes 的那种**：标记在
    # 闪烁暗相那一帧，亮度闸（见 _marker_lit）会把它放掉，单帧就查无此节点。
    # 读一次多帧窗口（1.62s）必然盖到亮相段，比"报没找到、停下车等人"便宜得多。
    if hit is None:
        fresh = read_view(g)
        hit = next((n for n in fresh["nodes"] if _near(n["box"], node["box"])), None)

    if hit is None:
        kinds = "、".join(n["kind"] for n in fresh["nodes"]) or "（一个都没认出）"
        return False, (f"{node['box']} 那一带没有节点，没点。"
                       f"（要找的是「{node['kind']}」）认到的是：{kinds}")
    if hit["kind"] != node["kind"]:
        log(f"    位置对上了，但标签读成「{hit['kind']}」，图里记的是"
            f"「{node['kind']}」—— 按位置走")

    x, y = icon_center(hit["box"])
    # **双击**：地图节点单击没反应，也不报错（用户确认 + 实测白点过一次）
    g.double_click(x, y)

    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        time.sleep(0.5)
        image = g.capture()
        if not g.see(地图界面, image):
            return True, f"点了 ({x},{y})，地图已关"
    return False, f"点了 ({x},{y})，等了 {timeout:.0f}s 地图也没关"
