"""《魂坠深境》的主循环：**一局接一局地打**，直到手动停止。

四层的分工（从下往上）：
    script/core/auto.py   工具层：Game 封装截图 / 识别 / 点击 / 等待
    script/recognizer.py  认屏层：**唯一一张"这一帧是哪一屏"的表**，只认不动
    script/{nav,nodes,combat,system}/*  界面层：一屏一个模块，负责"认出之后做什么"
    本文件                 流程层：开局 + 分发循环 + **跨局的循环**

两层循环，别混：
    · `play()`   —— **一局之内**：循环读取认出现在是哪一屏（recognizer.watch），
      分发给屏模块里认领它的那个 handler。本文件不再认识任何一屏，
      加策略请开 nav/ nodes/ combat/ system/ 里的文件。
    · `main()`   —— **跨局**：一局正常收尾（结算回主界面）就原地开下一局。
      用户 2026-10-02：「每次结束后都直接重新开始游戏, 直到手动停止」。
      **停只停两种**：手动 Ctrl-C，或者"这一局没正常打完"（停车等人 /
      未知界面 / 达到步数上限 / **战斗超时之后连"退出这一局"都走不通**）
      —— 后者是策略没定过或出事了，接着开新局会把日志和现场图盖掉，所以必须停。
      注意"打太久"本身**不再**是停车理由：用户 2026-10-03 定了
      「在一把战斗超过5min后,则直接退出该局」—— 放弃这一局、走完收尾、
      接着开下一局，见下面 `result == ABANDONED` 那段。

用法:
    python script/battle.py [难度]     # 缺省「噩梦9层」；Ctrl-C 停
    难度可选：普通 / 困难 / 险恶 / 严酷 / 极难 / 噩梦1层 ~ 噩梦9层

**启动时游戏停在哪都行**（用户 2026-10-02：「不管在何时, 启动脚本, 就继续直到
完成本局游戏」）：每一轮先认一眼现在是不是局内 —— 是就**接着这一局走完**，
不重启也不另开一局；不是（主界面 / 标题 / 弹窗这些局外屏）才回主界面开新局。
见 `main()` 里那段。

和 `debug/play.py` 的区别只剩一条：play.py **只跑一局**，跑完就退；
这里跑完接着开下一局，直到 Ctrl-C。续局能力两边现在都有。
"""

import io
import sys
import time
from pathlib import Path

# ⚠️ `line_buffering=True` 不能省：这个包装**会把 `python -u` 的效果抵消掉**。
# 试过：`python -u script/battle.py > log` 配一个不带 line_buffering 的
# TextIOWrapper，日志文件**空了一分多钟**（2026-10-02 23:5x 实测）——
# `-u` 只作用于**原来的** sys.stdout，换成新 wrapper 之后又变成整块缓冲，
# 夜里跑一局要等攒够 8KB 才落盘，出事了打开日志是空的。
if sys.stdout.encoding != "utf-8":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8",
                                  errors="replace", line_buffering=True)
if sys.stderr.encoding != "utf-8":
    sys.stderr = io.TextIOWrapper(sys.stderr.buffer, encoding="utf-8",
                                  errors="replace", line_buffering=True)

ROOT = Path(__file__).parent.parent.resolve()
sys.path.insert(0, str(ROOT / "script"))
import recognizer  # noqa: E402
from core.auto import Game  # noqa: E402
# NEED_STRATEGY 这条 import 2026-10-03 删了：撤掉「未知事件」那条例外之后它成了死
# import（`record()` 仍在 event.py 里跑，事件照常入册，只是不再由这里决定"把这局丢掉"）。
#
# `finish_run` 2026-10-03 又回来了 —— 这次是**为了战斗超时那条新规矩**：
# fight.py 把这一局退到结算屏就交回 `ABANDONED`，"之后怎么办"归这里，收尾由这里走。
from combat.fight import ABANDONED  # noqa: E402
from system.settlement import FINISHED, finish_run  # noqa: E402
from strings import 主界面, 噩梦9层  # noqa: E402
from shared.kit import log  # noqa: E402

GAME_PACKAGE = "com.chillyroom.containerofsoul.yw"


# ---------- 准备 ----------

def ensure_main(g):
    """不管当前停在哪个界面，把游戏弄回主界面。

    局内反向退出要连过 卡牌菜单 → 设置 → 放弃此轮 → 继续 → 结束探索 一长串界面，
    分支多、还容易卡在某个确认弹窗上；直接杀进程重开最省心，
    代价是冷启动 40~60s，只在确实不在主界面时才走这条路。

    **只在"游戏不在局内"时才该走到这里** —— `main()` 每轮开头先认一眼是不是
    局内屏，认得出就直接接着走，压根不会调进来。所以这里的活只剩两件：
    已经是主界面 → 原样返回；在局外别的屏（标题 / 公告 / 登录）→ 冷启动。
    一局跑完的收尾也不走这里，走 system/settlement.py（十几秒，不重启）。
    用户 2026-10-01：「不要重启, 在游戏中重启还是会继续当前游戏」。

    ---- 杀进程这条路**只在局外有效**（2026-10-02 实测撞上）----

    「不在主界面就杀进程」原来被当成万能的回主界面的路，其实它只在
    **游戏里没有未完成的一局**时管用：

        局内没有进度  → 冷启动落到主界面       ✓
        **有一局没打完 → 冷启动接着那局继续**  ✗ 永远到不了主界面

    2026-10-02 21:57 那次就是这么空转了 150 秒：游戏里那局是脚本自己先开的
    （21:52:08 有「坠入深境」、21:56:34 有「启动祭坛」），起了第二个进程时
    人还站在局内，于是杀了重开 → 冷启动恢复对局 → 脚本在「不是主界面也不是
    标题界面」之间转到超时，报「回主界面失败」退出。

    下面那道闸是**兜底**（防空转 150 秒），主路已经由 `main()` 的"先看在哪"
    走掉了：杀之前认一眼**是不是在局内**，认出东西就是在局内 → **不重启**，
    停下报清楚。不改任何策略，只是把「静默空转」换成「一句话说明白」。

    ⚠️ 认屏表**盖不住的局内屏**挡不住这一道（比如打开着的「卡牌菜单」面板
    不在表里），那种情况下 `main()` 也会判成局外、走到这里来白重启一次。
    要彻底堵上，得先有回主界面的第二条路（局内退出那条链），那条链还没做成
    脚本。**白重启一次的代价有限**：冷启动后游戏会恢复那局，下一轮 `main()`
    就看得出是局内、接着走，不会把进度弄丢。
    """
    if g.see(主界面):
        log("  已在主界面")
        return True

    inside = recognizer.identify(g)
    if inside is not None:
        log(f"  游戏里还有未完成的一局（当前停在：{inside.screen.name}）")
        log("  有局内进度时不重启")
        g.snap("ensure_main_inrun")
        return False

    log("  不在主界面，重启游戏（冷启动较慢）...")
    g.controller.post_stop_app(GAME_PACKAGE).wait()
    time.sleep(3)
    return g.start_game()


# ---------- 主循环 ----------

def play(g, max_steps=400):
    """一局的主循环：**循环读取**认屏 → 分发给认领它的 handler。

    状态机而不是线性流程——游戏里会随机撞上地点、战斗、结算，
    顺序无法预先写死，只能"看到什么处理什么"。

    返回的是**停下时的原因**，不一定都是终局：
        `FINISHED`（"结算"）/ `ABANDONED`（"放弃这一局"）是"这一局完了"
        —— 前者打通了，后者是战斗超时被放掉的，两者都由 `main()` 接着开下一局；
        "未知界面" / "达到步数上限" / "战斗超时（退出该局没走通）" 是**出事了**，
        得停下等人；带「等待…」的那些是**主动停车等人**，人处理完可以再调 play()
        接着跑。理由全部由各 handler 给出（等待选路 / 等待选卡 / 等待选护符 /
        等待事件 / 等待选路口 / 等待游艺 / 等待锻造 / 等待篝火 / 等待离开（××）/
        等待卡牌展示 / 等待事件结果），**本文件一个都不写死**——写死就又会漂回
        "认屏散在各处"的老路。（`FINISHED`/`ABANDONED` 是 import 来的协议值，
        不是这里现写的字面量，同理。）
    """
    steps = 0
    while steps < max_steps:
        steps += 1

        hit = recognizer.watch(g)
        if hit is None:
            log("  连续多轮认不出当前界面，停下")
            # **带时刻存**，别覆盖：停车现场图是这条判据唯一的物证（"每个识别都要
            # 有据可查"），撞第二次就把第一张盖掉 = 丢证据。从前一律叫
            # battle_unknown.png，一晚上过去只剩最后一张 —— 那正是要看的东西。
            # 2026-10-03 用户撤了"保留不认识的界面的截图"那条夜间规矩（「不需要
            # 保存截图了…当遇到不懂的, 再问我」）—— 撤掉的是"攒一晚上的截图给人
            # 过目"，这一张是**出事现场**，照存。
            # （`battle_unknown.png` 是旧名，现留在盘上没被再覆盖，screen_baseline
            #   的 CASES 里钉着它 = 大转盘屏那一帧。）
            g.snap(f"battle_unknown_{time.strftime('%H%M%S')}")
            return "未知界面"

        # "" = 处理完了继续；非空 = 这一屏要求停下等人，理由原样报给用户
        note = hit.screen.handler(g, hit)
        if note:
            log(f"  停下等人：{note}")
            return note

    return "达到步数上限"


# ---------- 入口 ----------

def main():
    difficulty = sys.argv[1] if len(sys.argv) > 1 else 噩梦9层
    g = Game().connect()

    # **每一轮先看游戏现在停在哪**（用户 2026-10-02：
    # 「不管在何时, 启动脚本, 就继续直到完成本局游戏」）：
    #
    #   认得出是局内屏（战斗屏 / 地图屏 / 各地点屏…即认屏表里那 26 行）
    #       → **接着这一局走**。不重启、不另开一局。这是第一轮最常见的情形：
    #         上一局没走完（脚本被人掐了、或者电脑重启），现在起脚本就把它续上。
    #   认不出（主界面 / 标题界面 / 公告页 / 登录…都是局外屏）
    #       → 回主界面，再开一局。
    #
    # 从前这一步是"一律先 `ensure_main()`"，那在局内就是个坑：
    # 不在主界面 → 杀进程重开 → 冷启动**接着那局继续** → 永远到不了主界面，
    # 空转 150 秒超时（2026-10-02 实测，见 ensure_main 的 docstring）。
    # 「先看在哪」这一条同时解掉两件事：既不白重启，也顺带满足了"接着走完"。
    #
    # **打完一局接着开下一局，直到手动停止**（用户 2026-10-02：
    # 「每次结束后都直接重新开始游戏, 直到手动停止」）。
    #
    # 停只停两种，**都不是"这一局打完了"**：
    #   1. **手动 Ctrl-C**；
    #   2. **不是正常打完**——停车等人（等待选路 / 等待事件 / …）、未知界面、
    #      步数上限、**以及"想放弃却放弃不掉"**（战斗超时之后退出那条链断了）。
    #      那些是"策略没定过"或"出事了"，得有人来看，
    #      **绝不能接着开新局把它们盖掉**（一局日志和现场图会被下一局冲掉）。
    #
    # 「打太久（战斗超时）就放弃这一局」是 2026-10-03 用户加的**唯一一条"不算正常
    # 收尾、但仍然接着开下一局"的路**（原话：「在一把战斗超过5min后,则直接退出该局」，
    # 之后又选了"退出后接着开下一局"）。它**不是**下面那条例外的复活：
    # 例外管的是"没定过策略"（那种要问人），这条路管的是"这一局已经废了、
    # 没必要等人"。见循环里 `result == ABANDONED` 那段。
    #
    # 2026-10-02 睡前曾为「没定过策略的事件」开过一个口子（放弃这一局、重开一局
    # 接着找），2026-10-03 用户撤掉了 —— 「当遇到不懂的, 再问我」，见下面
    # 那句 `result != FINISHED` 前面那段。**那条口子没回来。**
    #
    # 难度沿用同一档：规则是用户开局时给的，脚本不自己改，也不自己换。
    # **续跑的那一局不碰难度** —— 难度是它开局时定的，这里既改不了也不该改。
    #
    # 「重新开始」**不重启游戏进程**：收尾那条路（system/settlement.py 的
    # finish_run）已经把游戏带回主界面了，直接从那儿再进一局，十几秒；
    # 重启是 40~60s，而且用户 2026-10-01 说过「不要重启, 在游戏中重启还是会
    # 继续当前游戏」。
    run_no = 0
    try:
        while True:
            here = recognizer.identify(g)
            if here is not None:
                log(f"[1] 接着走：游戏里正走着一局，现在停在「{here.screen.name}」")
            else:
                run_no += 1
                log(f"[1] 回到主界面（准备开第 {run_no} 局：{difficulty}）")
                if not ensure_main(g):
                    # 两种停法，上面 ensure_main 已经分别说清楚了：
                    #   认屏表盖不住的局内屏 → 没杀、直接停；
                    #   真冷启动失败 → 报「未能进入主界面」。
                    log("    没能回到主界面，停下（不开新局）")
                    break
                log(f"[2] 开一局：{difficulty}（第 {run_no} 局）")
                if not g.enter_run(difficulty):
                    log("    坠入深境失败")
                    g.snap("battle_norun")
                    return 1

            log("[3] 开始自动推进")
            result = play(g)
            log(f"结果：{result}")
            g.snap("battle_end")

            # **「没定过策略的事件」那条例外，2026-10-03 用户撤掉了。**
            #
            # 2026-10-02 睡前定的是「如果遇到不认识的事件, 直接记录下来, 然后退出
            # 这把游戏, 重新开始」（动机是"让脚本自己认识一共有哪些事件"——那一夜
            # 靠它收进了「勒索」「月影幻象」两个）。2026-10-03 用户醒了之后改成
            # 一句：「**当遇到不懂的, 再问我**」—— 于是这条口子关掉，它和别的停车
            # 理由一样：**停下等人**。事件还是照样入册（nodes/event.py 的 record()
            # 会写进 events.json 并存 event_new_<事件名>.png），只是不再自作主张
            # 把这局丢掉。
            #
            # 于是"停只停两种"又回到原样：手动 Ctrl-C，或者"这一局没正常打完"。
            #
            # 2026-10-03 之后多了一条**不算正常收尾、但也不停车**的路：
            # `ABANDONED` = 这一局被放弃了（战斗超时）。用户当天定了
            # 「在一把战斗超过5min后,则直接退出该局」，并选了"退出后接着开下一局"。
            # fight.py 只把这一局**退到结算屏/主界面**为止（卡牌菜单 → 设置 →
            # 放弃此轮游戏），剩下那段收尾（继续 → 结束探索 ×2 → 获得物品 → 主界面）
            # 在这儿走 —— `finish_run` 幂等，从这条路上哪一屏接上都能走完，
            # 而且和正常打完走的是**同一条**收尾，不另开一条路。
            # 放弃的局**不记胜负**：它不是打通的，也不是打输的，所以这里直接调
            # finish_run，**不经过**结算屏那个 handler（那边会去读「仪式终结?」那行标题）。
            if result == ABANDONED:
                log("    这一局**放弃了**（战斗超时）—— 走完收尾，接着开下一局")
                finish_run(g)
            elif result != FINISHED:
                log("    **不是正常收尾**，停下等人")
                break

            # 收尾那一步**本该**把游戏带回主界面。没到就别去点「启动祭坛」——
            # 停在这儿让人看一眼，比闭着眼往下走强。
            if not g.see(主界面):
                log("    收尾没回到主界面，停下等人")
                g.snap("loop_notmain")
                break

            log("[4] 这一局收了 —— 接着开下一局（Ctrl-C 停）")
    except KeyboardInterrupt:
        log(f"手动停止（Ctrl-C）—— 这个进程一共开了 {run_no} 局")
        return 0

    return 0


if __name__ == "__main__":
    sys.exit(main())
