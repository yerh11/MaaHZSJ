def _stop(g, reason, hit=None, steps=None, snap=None):
    """停车留一份**文字记录** `debug/parks/<名字>.md`，再把 `reason` 原样交回去。

    用户 2026-10-15：「为停下等人逻辑, 专门编写一个文件, 记录当前环境与截图等」。
    从前一次停车只落现场图（`Game.snap()`）和滚屏里几行日志，事后回看要同时对着
    现场图、终端日志（多半已经滚出去）、外加"这一屏是哪一屏"得靠人看图认。
    现在多落一份自包含的记录：理由 / 现场图 / 停在哪一屏 / 命中了哪些节点 /
    屏上证据 / 第几步 / 分辨率 / 环境 / 最近 30 行日志。**内容与落点全在
    `shared/kit.py` 的 `report()`**，这里只是把手上有的料递过去。

    **为什么写在 `battle.py` 而不是 `park()` 里**（用户当天选的）：只有这一层
    手里有 `hit`（"停在哪一屏"就写在它身上）。`park()` 那九十多处调用点
    **一个都不改** —— 它们还是只管存图、打日志、把理由交回来。

    `snap` = 这份记录的文件名（**跟现场图同名**，用户当天选的形态）。三种传法：

      · `last_snap()` —— `play()` 那条路：某个 handler 刚 `park()` 过，
        它存的那张图就是这次的现场图（它 **没存图**时返回 None，记录改用理由当名字）；
      · 显式的名字 —— 本文件自己那几记 `g.snap(...)`，名字由调用点给
        （**不能**用 `last_snap()`：`battle_end` 是每轮都存、互相覆盖的，
        而当到"未知界面"这一步时 `last_snap()` 指的可能是上一局某次 `park` 留下的旧名）；
      · `None` —— 这一次确实没存图（只有 `达到步数上限` 那一条），
        记录就叫 `达到步数上限.md`（中文文件名，本工程有先例：现场图里就有
        `event_park_真龙现身_noclick.png`）。

    ⚠️ **只在这儿写，别在别处再写一份**：`main()` 里 `result != FINISHED` 那个
    `break` **故意不写** —— `play()` 是最内层的停车点，它已经写过一份了，
    在那儿再写一次就是拿同一个文件名覆盖同一份记录。**谁产生的理由谁写。**
    （`finish_run` 之后那一路同理：`loop_notmain` 那条是 `main()` 自己的理由，才归这儿。）

    记录**失败不影响停车**（`report()` 自己吞异常，见它的 docstring）—— 停还是照停。
    """
    screen = getattr(hit, "screen", None)
    report(g, reason,
           snapshot=snap,
           screen=getattr(screen, "name", None),
           matched=getattr(hit, "matched", None) or (),
           # `evidence` 只印出来给人看 —— `recognizer.py` 顶上写着它"只给日志和
           # describe 用，handler 不许拿它做动作"；记录是日志的延伸，不犯这条。
           evidence=getattr(hit, "evidence", None),
           steps=steps)
    return reason


def ensure_main(g):
    """不管当前停在哪个界面，把游戏弄回主界面。

    **只在"游戏不在局内"时才该走到这里** —— `main()` 每轮开头先认一眼是不是
    局内屏，认得出就直接接着走，压根不会调进来。所以这里的活只剩两件：
    已经是主界面 → 原样返回；别的屏（登录 / 认不出来的）→ **停下等人**。
    一局跑完的收尾也不走这里，走 system/settlement.py（十几秒，不重启）。

    **两个"局外屏"不归这里管、另有去处**（2026-10-14 补记）：「标题界面」由
    `main()` 的第 [0] 步点掉（见 `back_from_title`）、「公告 / 评价 / 签到 / 网络错误」
    由下面的 `close_blockers()` 清掉 —— 走到这一段还认不出的，才是真没见过的屏。
    从前那句写的是"标题 / 公告 …→ 停下等人"，那是刚拆掉重启那会儿的实情
    （标题界面那一半当天就补上了，见 `back_from_title`）。
    用户 2026-10-01：「不要重启, 在游戏中重启还是会继续当前游戏」。

    ---- 2026-10-14：杀进程那条路**整个拆掉了** ----

    用户当天连说两句：「将重启逻辑关掉」「将重启逻辑改为停下等人, 然后你进行处理」。

    从前这一步是 `post_stop_app` + `start_game`（杀进程再拉起，冷启动 40~60s）。
    它被当成万能的回主界面的路，其实只在**游戏里没有未完成的一局**时管用：

        局内没有进度  → 冷启动落到主界面       ✓
        **有一局没打完 → 冷启动接着那局继续**  ✗ 永远到不了主界面

    2026-10-02 21:57 那次就是这么空转了 150 秒：游戏里那局是脚本自己先开的
    （21:52:08 有「坠入深境」、21:56:34 有「启动祭坛」），起了第二个进程时
    人还站在局内，于是杀了重开 → 冷启动恢复对局 → 脚本在「不是主界面也不是
    标题界面」之间转到超时，报「回主界面失败」退出。

    中间加过一道闸：杀之前先 `identify()` 认一眼**是不是在局内**，认得出就不杀。
    可那道闸**盖不住认不出来的局内屏** —— 2026-10-14 07:50 那次，屏幕上正好是
    游戏的**竖屏加载画面**（日志里那句「截图形状不对（拿到 720x1280，该是
    1280x720）」就是它），`identify()` 一个都没认出来 → 闸没拦住 → 游戏里明明
    有一局没打完（已经打到第 26 场战斗）也照杀。

    ⇒ 那一步整个拆掉。现在**一律停下等人**：不杀进程、不拉起，现场留一张图
    （`ensure_main_stuck` / `ensure_main_inrun`）交给监视那一轮判断。
    代价：游戏真被关掉时脚本不会自己把它拉起来 —— 那是用户 2026-10-14 要的
    「尽量不要让脚本进行重启」。

    **当天又补了一小段：下结论之前先清一遍遮挡物、再等它一会儿**（见下面那段
    注释）。它不改"停下等人"这条规矩，只是别让"盖着一层弹窗（或还在加载）"
    被错报成"认不出来的未知屏"—— 16:09 那次「网络错误」对话框就是这么被
    错报、重启之后又停了第二次的。
    """
    if g.see(主界面):
        log("  已在主界面")
        return True

    # ---- 2026-10-14 加：认不出 ≠ 未知屏，底下可能只是**盖着一层遮挡物** ----
    #
    # 来历：当天 16:09 收尾那趟撞上「网络错误」对话框（现场帧
    # `finish_run_stuck.png`），脚本收尾超时停下；重启脚本之后，**这一步又把
    # 同一屏当成"认不出来的未知屏"停了第二次**。可它不是未知屏 ——
    # 遮挡物（公告页 / 评价弹窗 / 每日签到 / 网络错误）本来就是"盖在底下那屏
    # 上面"的东西，盖着的时候 `identify()` 与 `see(主界面)` 都会落空。
    # 所以这里先清一遍、再看底下是什么，别把"盖着一层弹窗"错报成"未知屏"。
    #
    # 清掉之后**多半还是加载过场**：点完「重试」，那趟落盘要重走一遍，而那张
    # 加载屏实测能慢到 **177s**（见 `system/settlement.py` 的 timeout 那段）。
    # 所以再给它一段时间自己走到主界面。**清不动、等不到 —— 照旧停下等人**，
    # 「不杀进程、不拉起」那条规矩没变（这一段里一次 `post_stop_app` 都没有）。
    if g.close_blockers():
        log("  清掉遮挡物之后，等它自己走到主界面（加载屏实测可达 177s）")
        if g.wait_for([主界面], timeout=180):
            log("  已回主界面")
            return True

    inside = recognizer.identify(g)
    if inside is not None:
        log(f"  游戏里还有未完成的一局（当前停在：{inside.screen.name}）")
        snap = "ensure_main_inrun"
    else:
        log("  不是主界面，也不是能认出来的局内屏")
        snap = "ensure_main_stuck"

    log("  **不重启**（不杀进程、不拉起），停下等人")
    # 停车记录在这儿写、不在 `main()` 里 —— 上面那两条 `snap` 只有本函数知道
    # 是哪一条，记录的名字（`debug/parks/ensure_main_stuck.md`）得跟着它走。
    _stop(g, "没能回到主界面", snap=snap)
    return False


def back_from_title(g, timeout=180):
    """停在**标题界面**时就点进去，等它画到"能认的一屏"再交回主循环。

    来历：`docs/zh_cn/使用文档.md` 第三节写的是「停在**局外**（主界面/**标题界面**/
    公告页）→ 回主界面，开新局」，这句在 HEAD 里就写着、工作区也没改过。兑现它的从前
    是 `ensure_main` 里那条 `post_stop_app + start_game()` —— `start_game()` 的循环里
    正有一句「到达标题界面，点击进入」。2026-10-14 用户让把重启逻辑整个拆掉
    （见 `ensure_main` 的 docstring），**这条路上就再没人点标题界面了**，于是规格里
    那半句悄悄少了一条：脚本停在这一屏、认出「不是主界面，也不是能认出来的局内屏」
    就停车等人（现场帧 `debug/screenshots/ensure_main_stuck.png`，2026-10-14 20:31：
    游戏被重新拉起来停在「点击任意处开始」，脚本 20:31:48 扫完 31 行认屏表、一行没中）。

    **点一下不是"拉起进程"**：这里一次 `post_start_app` 都没有，游戏本来就开着 ——
    与 2026-10-14 关掉的那条路（`post_stop_app` 杀进程再拉起）不是一回事，
    「不杀进程、不拉起」那条规矩一个字没动。

    点完**不能马上认屏**：后面是登录与地图加载（`启动族.json` 的 `标题界面` 节点上
    记着实测约 25s），那段时间里这一边与那边都是空的。所以在这儿等"底下有东西"为止，
    底下有三种可能、各有去处：
      · **主界面**           → 下面第 [1] 步的 `identify()` 认不出它（它不在认屏表里），
        照常走 `ensure_main()` 开新局；
      · **认屏表里任意一屏**  → 说得清"游戏里正走着一局"。点标题界面时，游戏里有一局
        没打完就会**接着那一局继续**（2026-10-02 21:57 实测，见 `ensure_main` 那份
        docstring 里「有一局没打完 → 冷启动接着那局继续」）—— 认得出来就接着走那一局，
        **不去开新局**，这正是 `main()` 第 [1] 步的活；
      · **一层遮挡物**        → 热更之后首次进去会弹公告页，公告页盖着主界面时上面
        两样都认不出，所以顺手清掉（`close_one_blocker` 本来就管这件事）。

    **这一屏一下点不进去，得点到它走**：头一下常常只是**触发 TapTap 登录**
    （游戏自己的 `MainMenu._OnLoginResult` 在那儿回调），屏**原地不动**，要再点一下
    才进去 —— 2026-10-14 那天实测就是两下：`debug/run_1014_auto4.log` 的
    08:06:35 点一下 → 08:06:45 再点一下 → 08:07:06 到主界面（**21 秒**）；
    当晚 20:42:06 那趟只点一下，`logcat` 里登录确实成功了
    （`trackLoginEvent {"_login_type":"TapTap","_status":"success"}`）而屏还停在
    「点击任意处开始」，脚本空等满 180s 落回 `ensure_main` 停车
    —— 那条「不补第二下」的头一版就是这么被证伪的。
    所以这儿点的是**从前 `start_game()` 那个循环的老规矩**：点一下 → 等它走 →
    还在就再点（间隔 6s 以上），一直到点出东西或超时。那不是新策略，是同一条规矩
    换个地方住 —— 从前它就写在 `start_game()` 的循环里。

    **再点之前"这一屏还在不在"由 `click_node` 自己把关**：它取不到「点击任意处开始」
    的框就一下都不发（`box_of` 返回 None），所以屏换掉之后不会把那一下落到新屏上。

    点不着 / 点了又没走都不当场下结论，一律交给超时那条路，由 `ensure_main()` 停车留图
    —— 免得同一个"回不到主界面"有两处出口、两套现场图名。
    """
    log("[0] 停在标题界面（游戏被重新拉起来了）→ 点进去")

    deadline = time.monotonic() + timeout
    last_try = -10.0               # 早于起点 ⇒ 头一下立刻就点
    clicks = 0
    while time.monotonic() < deadline:
        if g.see(主界面) or recognizer.identify(g) is not None:
            log("    底下有东西了，接着往下认")
            return True

        if time.monotonic() - last_try > 6:        # 两次"试着点"之间隔 6s 以上
            last_try = time.monotonic()
            if g.click_node(标题界面):
                clicks += 1
                if clicks > 1:
                    log(f"    第 {clicks} 下（头一下多半只是触发了登录）")

        g.close_one_blocker()      # 公告 / 评价 / 签到 / 网络错误 —— 清掉才看得见底下
        time.sleep(0.5)

    log(f"    {timeout}s 内没等到下一屏画出来（标题界面点了 {clicks} 下）")
    return False


