"""祭坛 —— 地图节点「祝福祭坛」进来看到的那一屏。

**当前策略：不碰「触摸祭坛」，直接点「离开地点」**（用户 2026-10-01 确认）。

「触摸祭坛 / 和梦境之主进行交易」是拿魂晶换赐福的入口，大概率接的正是
祭坛.json 里那套闲置节点（赐福卡-左/中/右、刷新、接受），但那套是给
**「始源之凝视」**（开局赐福三选一）建的，跟这一屏是不是一套界面还没验过。
所以：
    * pipeline 里 `触摸祭坛` 的 action 故意留成 DoNothing；
    * 本模块也不去点它。

**名字容易撞车**：本模块管的是地图节点「祝福祭坛」→ 屏名「祭坛」；
屏模块里没有别的"祭坛"，但 assets/resource/pipeline/祭坛.json
说的是「始源之凝视」，两码事。地图节点名 ≠ 屏名的对照表见 地点.json 头部注释。

**顺序**：地点专属必须排在通用「离开地点」之前（认屏表里这么排的），
否则通用分支会抢先把它点掉。
"""

from strings import 祭坛界面, 离开地点, 离开确认弹窗
from shared.reasons import (
    WAIT_LEAVE_ALTAR,
    )
from shared.kit import log, park


def is_altar(g, image):
    """这一帧**是不是真祭坛屏** —— 第二道闸：锚点读到的字必须**就是「祭坛」**。

    2026-10-02 栽在这：一张**事件屏**（标题「残垣壁画」，正文里有一行
    「这**祭坛**前的墙绘十分特别…」）被认成了祭坛屏。`祭坛界面` 的 roi
    是按真祭坛屏的标题位置卡的，可那张事件屏的正文从 y≈88 就开始，
    正好横穿 roi —— 读回 `这祭坛前的墙`（score 0.9999，box (90,177,129,22)）。
    认屏表里祭坛排第 10、事件屏排第 19，**祭坛先命中就轮不到事件屏**，
    一个真事件被当成地点屏，还停在了「等待离开（祭坛）」
    （现场 debug/screenshots/altar_stuck.png）。

    闸怎么定的 —— 从**引擎日志里的真实命中**量的（不猜）：
    真祭坛屏历次命中的 filtered_results（5 个不同场次，10-01 与 10-02）：
        (14,14,72,39)  (15,15,72,42)  (9,12,81,45)  (10,11,80,46)  (9,12,81,45)
        —— 文字**都是「祭坛」**两个字，框高 39~46
    那张事件屏的误命中：
        (90,177,129,22)  —— 文字「这祭坛前的墙」6 个字，框高 22
    两个数字都对得上：**文字长度 2 vs 6、框高 39~46 vs 22**。
    卡"文字就是「祭坛」"这一条，两条都拦得住（框高那条是同一件事的旁证）。

    ⚠️ 这是照「死亡屏」那条先例给地点屏加的第二道闸（`死亡屏` 也是被
    暗事件屏抢过屏，修法相同）。这道闸当时是**单边证据** —— 只证明"别的屏不再被抢走"。
    2026-10-02 23:19 真走进了祭坛屏（地图节点「祝福祭坛」），**这一边补上了**：
        · 脚本照常过了闸，走的还是「离开地点（不碰触摸祭坛）」；
        · 现场帧留下了：debug/screenshots/altar_ok.png（每次走进祭坛屏都覆盖它），
          标题「祭坛」两个字在左上角，正文「这座祭坛属于终之主 / 在这里献上魂晶，/
          它会给予你应有的赐福。」，左下「触摸祭坛」，右下「离开地点」；
        · debug/screen_baseline.py 里 `altar_ok.png` 那条就是**真祭坛屏的正例**
          （在那之前只有那张误命中的 `altar_stuck.png` 当反例）。
    留个心眼：真祭坛屏的正文里**「祭坛」二字也出现过**（「这座祭坛属于终之主」）——
    闸靠的是"读回来的字正好等于节点声明的 expected"，正文那处读回来是一整行、
    不等于「祭坛」两个字，所以照样拦得住；哪天锚点 roi 挪到正文上，这条会先红。
    """
    reco = g.probe(祭坛界面, image)
    if not reco or not reco.hit:
        return None

    # 该节点自己声明的 expected —— **不在这儿再抄一遍「祭坛」两个字**。
    # 判据就是"节点声明它认什么，读回来就得正好是它"，指望表那句话
    # 是节点自己的事，改锚点只改 JSON 一处。
    want = _expected_of(g, 祭坛界面)
    for r in (getattr(reco, "all_results", None) or []):
        text = (getattr(r, "text", None) or "").strip()
        if text and text in want:
            return {"标题": text}
    return None


def _expected_of(g, node):
    """这一行锚点在管线里声明的 `expected`，规整成一个字符串集合。"""
    param = g.resource.get_node_data(node)["recognition"]["param"]
    exp = param.get("expected") or []
    return {exp} if isinstance(exp, str) else {str(e) for e in exp}


def handle(g, hit):
    """点「离开地点」走人。"""
    if not g.click_when(离开地点, guard=hit.matched):
        # 认得出这一屏、却找不到唯一的出口 —— 停，别硬点别的（更别碰触摸祭坛）
        return park(g, WAIT_LEAVE_ALTAR, "altar_stuck",
            "祭坛：找不到「离开地点」 —— 停下等人（已存 altar_stuck.png）")

    # 存一张给基线用：**真祭坛屏的截图一张都没有**（见 is_altar 的 docstring），
    # 而 debug/screen_baseline.py 的待补清单里还挂着「祭坛屏」。
    # 2026-10-02 真撞上过一次，当时只有引擎日志里的 OCR 结果（文字「祭坛」、
    # 框 (14,14,72,39)）、没留下图 —— 从那以后每走一次存一张。
    # 文件名不带 `_` 前缀，所以 screen_baseline 的 frames/check 都会收它
    # （`_` 开头的是裁剪图，会被跳掉）。
    # **每次覆盖**：本来就只需要"一张能当正例帧的祭坛屏"，用最新的那张。
    g.snap("altar_ok")
    log("    祭坛：离开地点（不碰触摸祭坛）")
    # 什么都没做就走，多半不弹确认框；弹了就按规则清掉
    # 弹窗可能浮出来、也可能不浮（勾过「本局不再提示」之后就不再弹）——
    # 这条两行套路六个屏各抄了一遍，收到 Game.leave_after() 里了
    g.leave_after()
    return ""
