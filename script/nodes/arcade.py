def handle_morph(g, hit):
    """第 2 屏的另一支：移形变位（用户 2026-10-02 定的走法）。

    「**按 开始, 然后等停下, 固定第一格, 然后拒绝**」—— 前三步在这里做，
    「拒绝」是第 3 屏「全部奖励」上的按钮，照旧归 handle_result。

    **「等停下」现在是固定等 5 秒**（用户 2026-10-03：「b 移形变位…均改为等5s」，
    见 SPIN_WAIT）。此前是两道状态闸：① 等屏上出现「选择你的奖励」（那时用户说
    「你要等一会才能点」「大概6s左右」）；② 再 wait_still 等画面真停稳。
    两道闸都被这一句替掉了 —— 按完「开始」睡满 5 秒就按第 1 格。

    那 5 秒够不够是**它自己的判据说了算**：按完存一张 morph_ready.png，
    停不停得下来、那一刻画面是不是能点了，看那张图。点完若结果面板不来、
    「移形变位」也没走，照旧停车（下面那段）。

    进入姿势有两种：刚进来（有「开始」）和已经被按过「开始」、正等着选
    （只有「选择你的奖励」）—— 两种都接，脚本中途重启也能接着走；
    **后一种不再等 5 秒**（轮到的状态已经在了，重启前那 5 秒早就过完了）。
    """
    if g.wait_for([游艺选择奖励], timeout=1.0) is not None:
        log("    移形变位 → 已经轮到选（重启接回来的）—— 不等，直接点")
    elif g.click_when(游艺开始, guard=hit.matched):
        log("    移形变位 → 开始")
        log(f"    移形变位 → 等 {SPIN_WAIT:.1f}s 再点第 1 格")
        time.sleep(SPIN_WAIT)
    elif g.wait_for([游艺选择奖励], timeout=3.0) is not None:
        # 「开始」没按上，但屏上已经写着「选择你的奖励」—— 说明已经轮到我们了
        # （多半是脚本在动画中途重启过），不用再等。
        log("    移形变位 → 「开始」没按上，但已经轮到选 —— 不等，直接点")
    else:
        return park(g, WAIT_ARCADE, "arcade_stuck",
            "移形变位屏在：「开始」没认出来，「选择你的奖励」也没出来 —— 停下等人（已存 arcade_stuck.png）")
    g.snap("morph_ready")
    cx, cy = MORPH_CELL1
    log(f"    移形变位 → 选第 1 格 (x={cx}, y={cy})")
    g.click(cx, cy)
    # 点完等它走：结果面板盖上来也算（这一支的正常去处）；「移形变位」
    # 一直没走就是没点上，停车。
    if g.wait_for([游艺全部奖励], timeout=8.0) is None and g.see(游艺移形变位):
        return park(g, WAIT_ARCADE, "arcade_stuck",
            "点了第 1 格，「移形变位」还没走 —— 停下等人（已存 arcade_stuck.png）")
    return ""


def handle_rotation(g, hit):
    """第 2 屏的**第三支**：最佳轮换（2026-10-02 第一次见，用户当天定的走法）。

    用户 2026-10-02：「**点开始, 然后等6s, 点击选定了, 然后拒绝**」。

    这一支是**两段**（现场 debug/screenshots/ 的 unknown_screen.png 与 arcade_stuck.png）：

        1 刚进来：一排六格奖励（增加最大生命 / 刻写-XX印记 / 魂晶 …）
          + 底下一个「开始」——**没有「离开地点」、也没有「拒绝」**，
          能按的只有这一个按钮；
        2 按完「开始」约 6 秒，**屏不走**，只是换成"中间一张奖励牌 +
          「剩余2次机会」+ 换一个/选定了！" —— 用户定的走法是**直接按「选定了！」**
          （那两次「换一个」不用），奖励照收。

    「然后拒绝」是收下之后回到的**结果面板**，归 handle_result 那行（照旧
    「拒绝并触发战斗」）——本模块不重复一份。

    等的是**固定 5 秒**（用户 2026-10-03：「c 最佳轮换…均改为等5s」，见 SPIN_WAIT）
    —— 此前等的是就绪信号「选定了！」上屏（20s）+ wait_still(10s)，用户那个
    「然后等6s」是这段动画的通常耗时，现在直接睡满 5 秒再点。点的那一下仍走
    click_when：那一刻「选定了！」还没上屏的话，它会接着等到上屏（或超时停车），
    不会对着空屏点。
    进入姿势两种都接（刚进来 / 已经按过「开始」正等着选），脚本中途重启也能接上；
    **后一种不再等 5 秒**（轮到的状态已经在了）。
    """
    if g.wait_for([游艺选定了], timeout=1.0) is not None:
        log("    最佳轮换 → 已经轮到选（重启接回来的）—— 不等，直接点")
    elif g.click_when(游艺开始, guard=hit.matched):
        log("    最佳轮换 → 开始")
        log(f"    最佳轮换 → 等 {SPIN_WAIT:.1f}s 再点「选定了！」")
        time.sleep(SPIN_WAIT)
    elif g.wait_for([游艺选定了], timeout=3.0) is not None:
        # 「开始」没按上，但「选定了！」已经在屏上 —— 已经轮到我们了，不用再等。
        log("    最佳轮换 → 「开始」没按上，但已经轮到选 —— 不等，直接点")
    else:
        return park(g, WAIT_ARCADE, "arcade_stuck",
            "最佳轮换屏在：「开始」没认出来，「选定了！」也没出来 —— 停下等人（已存 arcade_stuck.png）")
    if not g.click_when(游艺选定了, guard=hit.matched):
        return park(g, WAIT_ARCADE, "arcade_stuck",
            "最佳轮换屏：要按「选定了！」时它又不在屏上了 —— 停下等人（已存 arcade_stuck.png）")
    log("    最佳轮换 → 选定了！")
    if not g.wait_gone(游艺选定了, timeout=8):
        return park(g, WAIT_ARCADE, "arcade_stuck",
            "按了「选定了！」，这一屏还没走 —— 停下等人（已存 arcade_stuck.png）")
    return ""


