def handle_result(g, hit):
    """第 3 屏：结果面板 → 默认「拒绝并触发战斗」（用户 2026-10-01 定）。

    「接受并离开」就在右边（实测 (760,578)），**不点它** —— 策略没定过。
    点完等面板消失再返回（从前是 sleep(2.5) 蒙）：不等到它走，
    下一轮可能认出同一屏、把按钮再点一次。

    **先把面板自己弹的那块奖励说明框收掉**（2026-10-03 加）：这块框是游戏
    弹在结果面板上的（"你得了什么"），盖着「全部奖励」那行标题 —— 2026-10-02
    的存档 debug/screenshots/morph_after_pick.png 上就盖着（用户当天记的
    「移形变位那一支的面板上那行标题被物品提示框盖着」）。它**不会自己走**，
    脚本点「拒绝并触发战斗」也点不掉它，于是跟着脚本一路走：第 4 屏 → 战斗
    （结果屏标题被它盖住）→ 地图 —— 到了地图就把标记和标签挡住，map_view
    读不出可前往、停车「等待选路」（用户 2026-10-03：「当前页面被上一次的
    游艺的信息阻挡了」）。
    收它的规矩用户 2026-10-02 就定过（「点击其他空白地方恢复」「不点掉就会
    一直挂着」），2026-10-03 补了「翻牌时不要双击」→ 走 auto.clear_info_box()
    **单击**空白处。放在按钮之前点：此刻面板是停稳的，而点完按钮屏就开始过场，
    那时候点空白落在哪一屏上不好说。
    """
    g.clear_info_box()
    if not g.click_when(游艺拒绝并触发战斗, guard=hit.matched):
        return park(g, WAIT_ARCADE, "arcade_stuck",
            "结果面板在，但「拒绝并触发战斗」没认出来 —— 停下等人（已存 arcade_stuck.png）")
    log("    游艺转盘 → 拒绝并触发战斗")
    # 等按钮**自己**退场：它在两块结果面板上都有。从前等的是「全部奖励」——
    # 移形变位那一支的面板上那行标题被物品提示框盖着（2026-10-02），
    # 等它就等于没等。
    if not g.wait_gone(游艺拒绝并触发战斗, timeout=8):
        return park(g, WAIT_ARCADE, "arcade_stuck",
            "点了「拒绝并触发战斗」，结果面板还在 —— 停下等人（已存 arcade_stuck.png）")
    return ""


def handle_wheel(g, hit):
    """第 2 屏：转盘屏 → 点「发射」让指针转起来。

    点完**等结果面板真的弹出来**再返回（从前是 sleep(3.5) 蒙）。
    实测按下那一刻 19:40:09、面板出现 19:40:12，约 3 秒；给 8 秒的余量。
    这个等同时堵住了一个没实测过的窗口：万一转得比 3.5s 久，旧代码下一轮
    会再点一次「发射」（那一帧上它是**灰的（禁用态，见 arcade_spin0）**，
    "点灰按钮会不会重新转一次"没有实测过）—— 现在只会在这一转走完之后
    才回到主循环，那个窗口根本不存在。
    """
    if not g.click_when(游艺发射, guard=hit.matched):
        return park(g, WAIT_ARCADE, "arcade_stuck",
            "转盘屏在，但「发射」没认出来 —— 停下等人（已存 arcade_stuck.png）")
    log("    游艺转盘 → 发射")
    # 结果面板的两种判据都收（理由同上：移形变位那一支的标题被提示框盖住）。
    if not g.wait_for([游艺全部奖励, 游艺拒绝并触发战斗], timeout=8):
        # **转完也可能压根不给打**（用户 2026-10-02：「游艺有可能不能触发战斗,
        # 直接离开就可以了」）。实测那次转完回到的是地点屏的第三段正文
        # （「没能让你尽兴真是抱歉…」，见本模块开头），右下角照旧「离开地点」，
        # 没有结果面板 —— 这不是"没转成"，是这一局不给你打。
        #
        # 判据里**先确认转盘屏已经走了**：万一「发射」压根没生效、转盘屏还在，
        # 那一屏上有没有「离开地点」没实测过 —— 不赌。真走了才放行，
        # 离开这件事交给「通用离开屏」去做（出口策略归它，本模块不重复一份点击）。
        if not g.see(游艺转盘) and not g.see(游艺发射) and g.wait_for([离开地点], timeout=3.0):
            log("    游艺 → 这次不能触发战斗（转完没有结果面板），直接离开")
            return ""
        return park(g, WAIT_ARCADE, "arcade_stuck",
            "点了「发射」，结果面板迟迟没出来 —— 停下等人（已存 arcade_stuck.png）")
    return ""


# 第 2 屏上「按完动作键之后等多久再动下一手」（秒）。**b / c / d 三支共用**；
# a（「发射」）不用 —— 那一支按下就自己转完，等的是结果面板。
#
# 来历：用户 2026-10-02 先单独给大转盘定了「**转动后等待3s再停止**」；2026-10-03
# 把三支一起改成 5 秒：「**b 移形变位, c 最佳轮换, d 大转盘均改为等5s**」。
# 于是三支都是"点完 → 等满 5 秒 → 点下一手"，**不再等就绪字、也不再 wait_still**
# （此前 b 等「选择你的奖励」、c 等「选定了！」各 20s，再各 wait_still 10s）。
#
# 这是用户给的**时长**，不是状态判据 —— 按完要等一会儿才轮到下一手，是玩法本身。
# 等满之后那一下仍走 click_when（现截现验）：按钮那一刻还没上屏，它会接着等到
# 上屏（或超时停车），不会对着空屏点。b 点的是固定格（没有可验的按钮），
# 那一下点完就存 morph_ready.png —— 5 秒够不够，看那张图说话。
SPIN_WAIT = 5.0


def handle_bigwheel(g, hit):
    """第 2 屏的**第四支**：大转盘（2026-10-02 第一次走进来，脚本当场报
    「未知界面」停下，现场 debug/screenshots/battle_unknown.png）。

    **这一支不专属于地图上写「盛大游艺」的节点**。此前这里写着"只有「盛大游艺」
    走得进来" —— 那是**一次样本**推出来的：2026-10-02 唯一一回见大转盘，恰好
    是从地图上写「盛大游艺」的节点进去的。用户 2026-10-03 推翻了它：
    「**大转盘并不是盛大游艺独有**」「**"盛大游艺"与普通"游艺"没有区别**」。
    也就是说，四支小游戏（幸运之锚 / 移形变位 / 最佳轮换 / 大转盘）由游戏这一局
    挑，**跟地图节点那四个字无关**；前两屏照旧同路（地点屏「游艺」→ 选第 1 格，
    走 events.json 那条），分岔只看第 2 屏上画的是什么。

    用户 2026-10-02 定的走法：**「转动轮盘」→ 转起来后等一会儿 → 按「停止」
    （那枚按钮上就写「停止」两个字）→ 之后照旧「拒绝并触发战斗」**。
    中间那一等的时长 2026-10-03 由 3 秒改成 5 秒（原话「d 大转盘均改为等5s」），
    见 SPIN_WAIT。

    和 handle_wheel 最大的不同：那一支按下「发射」**自己转完**，这一支
    **不会自己停**，得再按一下「停止」。所以这里是**两段点击**，而且两段
    都在本函数里做完才返回 —— 中途返回的话，下一轮会重新认出「大转盘」、
    把「转动轮盘」再按一次（正转着的轮盘上那枚按钮还在不在、按下去会怎样，
    **没实测过，不赌**）。

    进入姿势两种都接（同 handle_morph / handle_rotation）：刚进来（有
    「转动轮盘」）、和已经转过正转着（只有「停止」）——脚本中途重启也能接上。

    两处点击都拿 `hit.matched` 当守卫（同帧耦合）：按「转动轮盘」时要求
    「大转盘」标题也在这帧上，按「停止」时同理。**万一标题在转动时被盖住**，
    这里会停车而不是接着点 —— 那是可接受的方向：停一次看得见、查得到，
    乱点一次看不见。
    """
    # 按下「转动轮盘」那一刻的时刻；中途重启接回来的没有这一刻，留 None。
    spun_at = None

    # 已经转着了（重启接回来的姿势）就跳过第一段，直接去停它。
    if g.wait_for([游艺停止], timeout=1.0) is None:
        if not g.click_when(游艺转动轮盘, guard=hit.matched):
            return park(g, WAIT_ARCADE, "bigwheel_stuck",
                "大转盘屏在，但「转动轮盘」没认出来 —— 停下等人（已存 bigwheel_stuck.png）")
        spun_at = time.monotonic()
        log("    大转盘 → 转动轮盘")

    # **转起来之后等满 5 秒再停**（SPIN_WAIT；用户 2026-10-03「均改为等5s」，
    # 此前是 3 秒）。从**按下转动**那一刻起算 —— 中途重启接回来的没有那一刻
    # （spun_at is None），就从现在起算：宁可多转一会儿，也不要在没转够的时候
    # 按「停止」。
    waited = 0.0 if spun_at is None else time.monotonic() - spun_at
    if waited < SPIN_WAIT:
        time.sleep(SPIN_WAIT - waited)
    log(f"    大转盘 → 等了 {max(waited, SPIN_WAIT):.1f}s，按「停止」")

    if not g.click_when(游艺停止, guard=hit.matched):
        return park(g, WAIT_ARCADE, "bigwheel_stuck",
            "等满了，「停止」这一下没点上 —— 停下等人（已存 bigwheel_stuck.png）")
    log("    大转盘 → 停止")

    # 停完的去处照旧是结果面板（「拒绝并触发战斗」），归 handle_result 那行。
    # 结果面板的两种判据都收，理由同 handle_wheel（移形变位那一支的标题会被
    # 物品提示框盖住）。
    if g.wait_for([游艺全部奖励, 游艺拒绝并触发战斗], timeout=8.0) is None:
        # 转完也可能压根不给打 —— 用户 2026-10-02：「游艺有可能不能触发战斗,
        # 直接离开就可以了」。判据同样是**先确认这一屏真的走了**，走了才放行，
        # 「离开地点」交给通用离开屏去做（出口策略归它，本模块不重复一份点击）。
        # 「停止」也一起看：转着的那一帧上标题可能不在，光看标题会判断错。
        if (not g.see(游艺大转盘) and not g.see(游艺停止)
                and g.wait_for([离开地点], timeout=3.0)):
            log("    大转盘 → 这次不能触发战斗（停完没有结果面板），直接离开")
            return ""
        return park(g, WAIT_ARCADE, "bigwheel_stuck",
            "点了「停止」，结果面板迟迟没出来 —— 停下等人（已存 bigwheel_stuck.png）")
    return ""


# 「移形变位」第 1 格（2×3 网格的左上格）中心 `MORPH_CELL1` 已搬进
# `shared/coords.py`（量法与复核图见那边）。换位只换牌面、格子位置是死的，
