"""篝火 —— 地图上「事件」节点进来可能是这一屏。

**策略**（用户 2026-10-01 定，2026-10-02 补了满血那条）：
    「激活护符」花 3 魂晶 —— 数够了就先点它（进护符选择界面，那屏另说）；
    点不动（魂晶不够 / 护符槽位满了选不出）就试「坐下休息」回血；
    再点不动就「离开地点」走人。**满血时「坐下休息」是灰的**，也属于
    "没有选项"，一样直接离开、不停车 —— 用户 2026-10-02：「当满血时,
    无法"坐下休息", 如果没有选项, 直接离开就可以了」。满血靠底栏那个
    「当前/上限」（节点 `生命值`，见 地点.json）判，读不到就当作未知、照旧试。
    三个按钮**全都认不出来**才是异常，才停车等人（见 handle 末尾）。

其它地点各有各的文件，对照表见 assets/resource/pipeline/地点.json 的头部注释。

**顺序**：地点专属必须排在通用「离开地点」之前（认屏表里这么排的），
否则通用分支会抢先把它点掉——本模块就踩过这个坑：策略写在 debug/campfire.py
里，却一直没接进 play()，等于从没执行过。
"""

from strings import 坐下休息, 激活护符, 确认选择, 离开地点, 离开确认弹窗, 魂晶数量, 生命值, 篝火界面
from shared.reasons import (
    WAIT_CAMPFIRE,
    )
from shared.kit import log, park

AMULET_COST = 3  # 「激活护符」的价格（魂晶）

# 这里**曾经有过一个 `SKIP_ACTIVATE` 开关**（2026-10-01 加，2026-10-04 拆掉）。
#
# 来历：2026-10-01 用户说
#     「不进行替换，当满时，直接走，后面我会改成四个，现在直接离开就可以了」
# 当时 5 个护符槽位**全满**，一激活就必然要替换掉一个，而用户不替换；那条路点到底
# 会弹「同一槽位只能存在一个护符 / XX 将被替换为 YY」的确认框，脚本对它的是/否
# **还没量准**（用户说「下次遇到再说」）。所以整支跳过了，开关当时是 `True`。
#
# 2026-10-02 他又说「不是让你在篝火激活护符吗」—— 篝火就该走「激活护符」这一支，
# 于是开关改回 `False`：先点「激活护符」（花 `AMULET_COST` 魂晶）进护符选择界面，
# 那一屏由 script/nodes/amulet.py 按框上印的号 1→2→3→4→5 挑一个装上；要是这局槽位
# 其实还是满的，会走替换流程，amulet.py **停下等人**，不会替人点。
#
# 2026-10-04 拆掉：开关定在 `False` 之后，`if not SKIP_ACTIVATE and ...` 恒真、
# 「坐下休息」那句日志的分支恒假 —— 留着就是一处**恒真/恒假**。现在想跳过激活
# 只能改代码，不再有"翻一下常量"这个口子。
#
# 更讲究的做法是让脚本自己认出"满了"（比如 OCR 左列那几个「空槽位」），
# 但那一屏的整屏 OCR 实测很不稳（5 个号里只读出来 1 个），先不拿它当判据。

# 「激活护符」这一支的等待上限。「坐下休息」和「离开地点」紧跟着，
# 各自只给自己那一小段 —— 一帧缺席不等于这一支不可用，见 handle 的注释。
WAIT_ACTIVATE = 4.0
WAIT_REST = 3.0
WAIT_LEAVE = 3.0


def _confirm(g):
    """选项是**两段式**：点选项本身只是高亮，中间浮出的「确认选择」才真正生效
    （用户指出的）。只点第一下会停在原地，看着像"点了没反应"。

    点完**等「确认选择」自己消失**再返回：它是"这一下生效了"的直接证据。
    不等的话下一轮可能还认出篝火、把选项又点一次——公告页连点就是这个病。
    """
    if not g.click_when(确认选择, timeout=3.0, guard=(篝火界面,)):
        log("    没等到「确认选择」")
        return False
    log("    → 确认选择")
    g.wait_gone(确认选择, timeout=4.0)
    return True


def handle(g, hit):
    """在篝火界面做一次决策并执行。

    哪一项真点了，地上那句 print 里写着；返回值只管"要不要停"。

    **先等面板画出来，再读魂晶**（新契约第 3 条）。2026-10-02 的事故就是
    "屏认出来了、魂晶也读了，可选项面板还没画上来"：那一帧上三个按钮一个都
    找不到，脚本停车报「三项都没认出来」。反过来更危险——要是面板慢一点、
    「激活护符」一帧缺席就当成"这一支不可用"，那就是**替用户改策略**。

    但也不能等死：休息过之后两个选项**本来就点不了**（节点配不上是正常状态，
    见 debug/run_1002d.log），那不是"没画出来"。所以这里的等法是：
    先给面板一小段时间（读魂晶要落在一张画完的屏上），剩下的等待
    交给下面**每一次 click_when** 自己带着 —— 一帧缺席 ≠ 这一支不可用。
    """
    # 面板没画完时读魂晶可能读到残缺的屏；先等一小会儿（等不到也继续，
    # 后面还有 click_when 接着等）
    g.wait_for([激活护符, 坐下休息], timeout=2.0)

    crystals = g.read_number(魂晶数量)
    log(f"    魂晶 {crystals}（激活护符要 {AMULET_COST}）")

    # 读不到魂晶时不敢判断"不够"，宁可当作够——点错了顶多弹个提示，
    # 而误判成"不够"会白白错过一个护符
    if crystals is None or crystals >= AMULET_COST:
        if g.click_when(激活护符, timeout=WAIT_ACTIVATE, guard=hit.matched):
            log("    → 激活护符")
            # 没等到「确认选择」不算停：多半只是那一下没落上，下一轮还会走到这儿
            _confirm(g)
            return ""

    # 满血时**不试**「坐下休息」：那一行的按钮是灰的，点下去不报错、也不浮出
    # 「确认选择」，而旧写法把"没等到确认"当成"这一下没落上"、`return ""` 接着
    # 循环 —— 满血撞上去就是**死循环**（debug/run_1002z.log:297 起，同一屏空转了
    # 35 轮以上）。用户 2026-10-02 定的走法：没有选项就直接离开。
    # 生命值读不到时返回 None：**未知不等于不满**，照旧试一下（宁可多点一下，
    # 也别因为一次 OCR 打嗝就白白错过回血）。
    hp = g.read_fraction(生命值)
    full = hp is not None and hp[0] >= hp[1]
    if hp is None:
        log("    生命值没读出来 —— 未知，照旧试一下「坐下休息」")
    else:
        log(f"    生命值 {hp[0]}/{hp[1]}" + ("（满血，不试「坐下休息」）" if full else ""))

    if not full and g.click_when(坐下休息, timeout=WAIT_REST, guard=hit.matched):
        log("    → 坐下休息（魂晶不够或护符不可选）")
        if _confirm(g):
            return ""
        # 选上了却没浮出「确认选择」= 这按钮其实点不动（满血就是这么表现的，
        # 只是生命值那一栏没读到）。**不再原地重来**，往下走「离开地点」。

    # 「坐下休息」点不动**不是异常**，是三种正常情况之一：**满血**（按钮是灰的，
    # 用户 2026-10-02 指出的）、魂晶不够、护符不可选。三种都该走同一个出口 ——
    # 没有可点的选项就直接离开，不停车。
    if g.click_when(离开地点, timeout=WAIT_LEAVE, guard=hit.matched):
        log("    → 离开地点（没有可点的选项：满血 / 魂晶不够 / 护符不可选）")
        g.leave_after()
        return ""

    # 三项一个都没认出来：这一屏认得（认屏表说了），却没有出口 —— 停下问人。
    # 从前这里是往下掉、转满 400 轮报"达到步数上限"——**停下来问**比空转有用。
    return park(g, WAIT_CAMPFIRE, "campfire_stuck",
        "三项都没认出来 —— 停下等人（已存 campfire_stuck.png）")
