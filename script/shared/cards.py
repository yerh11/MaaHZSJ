"""牌名这件事：**保留名单 + 两条比对规则** —— 三个屏共用一份。

答案只有一句：哪些牌不许动（`KEEP`）、卡名怎么比（`base_name`）、
一段 OCR 出来的字像不像卡名（`looks_like_name`）。

**为什么住在 `shared/`**：这份名单最早在 `nodes/cardpick.py`（2026-10-03 事件那条
路：「选择 无畏斧,莽撞头槌,隐痛 之外的卡牌移除」）。2026-10-04 商店那条路要的是
**同一张单子**，那天把名单留在 cardpick 里、只在注释里写了句"别再抄第二份"。
同一天晚些时候「移除卡牌」真点下去，弹出的是**另一屏**（标题「你的卡组」，
走法在 `nodes/deck.py`），它要的还是这张单子 —— 而屏模块之间不许互相 import
（`tools/check_screens.py` 第 1 条钉着），名单就只能往公共层挪。

于是：**名单和比对规则只有这一份**，`cardpick`（事件的选卡屏）和 `deck`
（商店的销毁面板）各自 `from shared.cards import ...`。

本模块只 import `strings` —— 卡名是游戏里的字，从那儿取。
"""

from strings import (卡名_无畏斧, 卡名_莽撞头槌, 卡名_隐痛,
                     卡面_隐痛, 卡面_无畏斧, 卡面_无畏斧_熔岩, 卡面_莽撞头槌)

# 保留名单（用户 2026-10-03：「选择 无畏斧,莽撞头槌,隐痛 之外的卡牌移除」）。
# 名单**之外**的牌才动手。三个屏共用这一份，见模块 docstring。
KEEP = (卡名_无畏斧, 卡名_莽撞头槌, 卡名_隐痛)

# 同一份名单的**图形版**：卡面上没有名字，所以销毁面板上"这一格是保留名单里的牌吗"
# 靠对图（管线节点见 卡面.json，实测余量见 debug/_cardtpl_check.py）。
# 一个卡名可能对应**几张图**（无畏斧有原形态和升变后的熔岩形态），所以这是"图"的
# 名单、`KEEP` 是"名"的名单 —— **两者必须一起改**：
#   · 名单上加了牌 → 这儿补它的卡面（先存帧、量准了再加，见 卡面.json 的抬头）
#   · 名单上删了牌 → 这儿的卡面要一起删，否则那张牌会被当成"要留的"跳过，白白不销毁
KEEP_TEMPLATES = (卡面_隐痛, 卡面_无畏斧, 卡面_无畏斧_熔岩, 卡面_莽撞头槌)


def base_name(name):
    """卡名去掉升级后缀 `+`：`无畏斧+` 和 `无畏斧` 是**同一种牌**。

    管线「卡牌名」那条的原话：「同名卡可能有 + 后缀（升级版），比对时按'去掉 +
    的前缀'来认」。实测这局读出来的是 `无畏斧+`、`莽撞头槌+`。
    比对 `KEEP` 之前一律先过这一道。
    """
    return (name or "").rstrip("+").strip()


def looks_like_name(text):
    """这段字像不像卡名（至少两个汉字）。

    没选中任何卡时，详情面板那块 roi 会读到别的屏上的零碎字（实测整片底色被
    读成 `一の`，score 0.161），加这道闸挡噪声 —— 跟事件屏的
    `_looks_like_title` 一个道理：读到的字不像名字 = **没读到**，
    调用方据此走"不猜"那条路，别把噪声当成一张牌的名字。
    """
    return sum(1 for ch in text if "一" <= ch <= "鿿") >= 2
