"""商店屏 ↔ 销毁卡牌面板之间的那点交接 —— **全脚本唯一一处跨屏状态**。

**为什么非得有这么个东西**：用户 2026-10-04 给商店定的出口是

    「点击"移除卡牌" 移除"隐痛\\无畏斧\\莽撞头槌"之外的卡牌
      (金币不足时或没有可移除时离开)」

"还要不要接着销毁"这个判断**长在销毁面板上**（`nodes/deck.py` 才数得出还有没有
名单外的牌），可**要动手离开的是商店屏**（`nodes/shop.py` 才点得到「离开地点」）。
而等控制回到商店屏时，"刚才销毁了一张"和"一张都没销毁"**长得一模一样**——
都是又站回商店屏，一个字都没变。所以这个事实必须有个地方放一下。

屏模块之间不许互相 import（`tools/check_screens.py` 第 1 条钉着，环在 import 期就炸），
于是放在这儿：两边各自 `from shared import gridstate`，是**唯一**一条合法的跨屏通道。

| 格子 | 谁写 | 谁读 | 回答什么 |
|---|---|---|---|
| `_more` | `deck`（退回商店之前 / 销毁之后面板自己收了） | `shop.handle`（进门读一次） | **还要不要再点一次「移除卡牌」** |
| `_asked` | `shop.handle`（点下「移除卡牌」那一刻） | `shop.handle`（下一轮进门时）；`deck` 写答复时顺手清掉 | **商店问过、面板还没答** —— 这期间要是又看见商店屏，"到底进没进面板"得再确认一眼 |

（2026-10-04 早些时候这里还有第三格 `_from_shop`：那时"「移除卡牌」点下去是哪一屏"
没人量过，只好挂一面"这一趟是商店叫来的"的旗，让卡组屏读不到移除副标题时停车。
当天晚些时候面板本身量清楚了（`nodes/deck.py` 的 docstring）—— 它有自己的认屏行，
商店再也不会把控制交给 `cardpick`，那格旗和它守的那条停车路就一起删了。）

**`_asked` 为什么非得在这儿、不能留在 shop.py 里**：它要**面板来清**。商店点完
「移除卡牌」就 `return ""`，下一轮认屏表重新分发那一帧 —— 要是那一帧面板还没画出来
（淡入中），先认出来的还是商店屏，商店就会以为"点了却没进去"。这面旗就是让商店知道
"我刚问过"，好**等一等**再判。而"面板已经处理完了"这件事只有面板自己知道，它写
`_more` 的时候顺手把这面旗清掉（`mark()` 里）—— 留在 shop.py 里就没法清，会出现
"面板答完走了、下一家商店一进门就以为'上一轮点过了'直接走人"。

**只放布尔**（不放"谁叫来的"那句话）：放字会跟 `check_strings.py` 那条"脚本里不许有
裸字符串"打架 —— 那游戏里的字该从 `strings.py` 取，而这里根本不需要说名字，说名字是
`deck` 那边写给人看的停车描述的事。本模块也照 `kit.py`/`reasons.py` 的规矩
**不 import 任何东西**。

⚠️ **别往这儿装别的东西**：它只服务上面那张表，别的走 `kit.py` / `reasons.py`。
状态是**模块级全局**，跟着进程走（`battle.py` 一个进程跑好几局），所以每格都必须在
下一次写之前被读走或被显式清掉，不能攒着过一局。
"""

# 面板那一趟的结果：True = 还销毁得动（商店再点一次「移除卡牌」）
# / False = 到此为止（商店点「离开地点」）
# / None = 面板还没答（还没跑过，或正跑着）
_more = None
# 商店问过没有：True = 点过「移除卡牌」了，面板还没答
_asked = False


def mark(more):
    """销毁面板写：这一趟**还接不接着销毁**。`deck` 两道出口各写一次。

    顺手把 `_asked` 清掉 —— 面板答了，商店那一问就不再悬着（见模块顶部那张表）。
    """
    global _more, _asked
    _more, _asked = bool(more), False


def ask():
    """商店屏写：我点过「移除卡牌」了，等面板答复。"""
    global _asked
    _asked = True


def take():
    """商店屏读：`(面板的答复, 商店问过没有)`，**读走就清**。

    答复 True（还销毁得动）/ False（没得销毁了，或金币不够）/ None（面板还没答）。
    商店靠 `False` 判"该走了"，靠 `None + 问过` 认"点了却没进面板"。
    """
    global _more, _asked
    out = (_more, _asked)
    _more, _asked = None, False
    return out


def forget():
    """把两格一起清干净 —— **商店每次离开时、面板退到别处时各调一次**。

    为的是同一局里的**下一家商店**：不清的话 `_more` 还留着上一趟的 True，
    下一家一进门就当成"面板说还能销毁"，接着点「移除卡牌」——运气好只是白点一下，
    运气不好（那家商店没得销毁）就在那儿来回点；`_asked` 留着同理会让它一进门
    就"当作金币不足"直接走人。清干净就从头来过。
    """
    global _more, _asked
    _more, _asked = None, False
