"""脚本用到的**全部游戏字符**，一处一个名字 —— 脚本与游戏/管线之间的那本字典。

为什么要有这个文件：

1. **一个东西只有一个名字。** 脚本认的是游戏印在屏幕上的字，那个字就是常量名本身
   （`离开地点 = "离开地点"`）—— 不做英文翻译，也不起外号。想知道"脚本到底依赖
   游戏里哪些字"，把这一个文件从头读到尾就完了，不用翻 13 个 py。
2. **改名只改一处。** 管线里节点改名、或游戏改版换了文案，改这里一行，所有调用点跟着走。
3. **打错字当场报。** 直接写 `g.click_node("离开地")` 要跑到那一步才发现；
   写成常量，名字写错在 import 时就 NameError。
4. **有机器在盯着。** `python tools/check_strings.py` 核对六件事：这里的每个节点名都得
   在管线里真存在；每档难度都得有对应的 `难度-<名字>` 节点；每个词条都得写进
   map.py 的词典（NODE_KINDS）；脚本里不许再有漏网的裸字符串；用到的常量必须 import 过；
   这里也不许留下没人引用的死名字。跑一遍半秒，退出码 0 才算数。

用法 —— 脚本里就这样写，**别再写字面量**：

    from strings import 离开地点, 仪式配置界面
    g.click_node(离开地点)
    if g.see(仪式配置界面, image): ...

命名规则：**常量名 = 管线里的节点名（或游戏里印的字），一字不改。** 只有一种例外：
节点名里带 `-` 的（`卡牌-无畏斧`），Python 标识符不许有减号，换成下划线，但**值仍是原文**
（`卡牌_无畏斧 = "卡牌-无畏斧"`）。

**这里只收整条的"词条"。** 解析用的碎字（auto.py 里把「严酷」拆成「严」「酷」那种）
留在原地的代码旁边；日志文案、docstring 同理 —— 那些不是"脚本跟游戏对暗号用的字"。
事件表（`script/events.json`）也不并进来：它本来就是一张按标题索引的表，键就是标题。
"""

